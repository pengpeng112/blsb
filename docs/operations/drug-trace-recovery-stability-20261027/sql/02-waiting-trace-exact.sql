-- 候选只读核查：以r10同样的三键取原扫码行，按原始值分组，不猜状态含义。
-- OUT、IS_DELETED、SPLIT_FLAG的业务解释须用已批准字典/原厂证据确认。
-- snapshot_time_gmt8是该单旧采集时点换算到北京时间，不能使用发送时点代替。
SELECT T.IN_OUT_TYPE AS DIRECTION_RAW,
       T.IS_DELETED AS DELETED_RAW,
       T.SPLIT_FLAG AS SPLIT_RAW,
       COUNT(*) AS TRACE_ROWS,
       SUM(CASE WHEN TRIM(T.T_TRACE_CODE) IS NOT NULL THEN 1 ELSE 0 END) AS NONEMPTY_T_ROWS,
       SUM(CASE WHEN TRIM(T.F_TRACE_CODE) IS NOT NULL THEN 1 ELSE 0 END) AS NONEMPTY_F_ROWS,
       SUM(CASE WHEN TRIM(T.S_TRACE_CODE) IS NOT NULL THEN 1 ELSE 0 END) AS NONEMPTY_S_ROWS,
       SUM(CASE WHEN T.CREATE_TIME > TO_DATE(:snapshot_time_gmt8, 'YYYY-MM-DD HH24:MI:SS')
                THEN 1 ELSE 0 END) AS CREATED_AFTER_SNAPSHOT,
       SUM(CASE WHEN T.MODIFY_TIME > TO_DATE(:snapshot_time_gmt8, 'YYYY-MM-DD HH24:MI:SS')
                THEN 1 ELSE 0 END) AS MODIFIED_AFTER_SNAPSHOT
FROM DRUG_USER.MED_TRACE_RECORD T
WHERE T.TRACE_BILLNO = :trace_billno
  AND T.PRESC_DATE = TO_DATE(:presc_date_s, 'YYYY-MM-DD HH24:MI:SS')
  AND T.STORE_CODE = :store_code
GROUP BY T.IN_OUT_TYPE, T.IS_DELETED, T.SPLIT_FLAG
