-- 候选只读核查：一张处方的完整三键，不查询患者字段。
-- 参数PRESC_DATE必须保留秒；PRESC_NO绑定NUMBER；药房保留前导零。
SELECT COUNT(*) AS MASTER_ROWS,
       MIN(M.PRESC_SOURCE) AS PRESC_SOURCE_RAW,
       MIN(M.FLAG) AS FLAG_RAW,
       MIN(M.REFUND_FLAG) AS REFUND_FLAG_RAW,
       SUM(CASE WHEN M.DISPENSING_DATETIME >= DATE '2026-10-26'
                 AND M.DISPENSING_DATETIME < DATE '2026-10-27'
                THEN 1 ELSE 0 END) AS IN_AUTHORIZED_DAY
FROM PHARMACY.DRUG_PRESC_MASTER M
WHERE M.PRESC_DATE = TO_DATE(:presc_date_s, 'YYYY-MM-DD HH24:MI:SS')
  AND M.PRESC_NO = :presc_no
  AND M.DISPENSARY = :store_code
