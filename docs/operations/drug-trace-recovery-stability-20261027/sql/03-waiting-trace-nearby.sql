-- 候选只读诊断：同一TRACE_BILLNO且创建时间最多48小时，最多取1001行。
-- 用于找三键不一致的证据，绝不能据此改生产JOIN或把无主单码直接上传。
-- TRACE_BILLNO有2026-10-19索引证据；执行前DBA复核索引和现有执行计划。
WITH BOUNDED_TRACE AS (
    SELECT T.PRESC_DATE, T.STORE_CODE, T.T_TRACE_CODE
    FROM DRUG_USER.MED_TRACE_RECORD T
    WHERE T.TRACE_BILLNO = :trace_billno
      AND T.CREATE_TIME >= TO_DATE(:begin_time, 'YYYY-MM-DD HH24:MI:SS')
      AND T.CREATE_TIME < TO_DATE(:end_time, 'YYYY-MM-DD HH24:MI:SS')
      AND ROWNUM <= 1001
)
SELECT COUNT(*) AS EXAMINED_ROWS,
       CASE WHEN COUNT(*) >= 1001 THEN 1 ELSE 0 END AS MAY_BE_TRUNCATED,
       SUM(CASE WHEN B.PRESC_DATE = TO_DATE(:presc_date_s, 'YYYY-MM-DD HH24:MI:SS')
                 AND B.STORE_CODE = :store_code THEN 1 ELSE 0 END) AS EXACT_KEY_ROWS,
       SUM(CASE WHEN B.PRESC_DATE <> TO_DATE(:presc_date_s, 'YYYY-MM-DD HH24:MI:SS')
                  OR B.PRESC_DATE IS NULL THEN 1 ELSE 0 END) AS OTHER_DATE_ROWS,
       SUM(CASE WHEN B.STORE_CODE <> :store_code OR B.STORE_CODE IS NULL
                THEN 1 ELSE 0 END) AS OTHER_STORE_ROWS,
       SUM(CASE WHEN TRIM(B.T_TRACE_CODE) IS NOT NULL THEN 1 ELSE 0 END) AS NONEMPTY_T_ROWS
FROM BOUNDED_TRACE B
