-- LEFT JOIN仅用于诊断保留原扫码记录；不能据此直接让无主单记录上报。
SELECT T.RECORD_ID,T.PRESC_DETAILID,T.T_TRACE_CODE,
       T.TRACE_BILLNO,T.PRESC_DATE,T.STORE_CODE,
       T.IN_OUT_TYPE,T.IS_DELETED,T.SPLIT_FLAG,
       CASE WHEN M.PRESC_NO IS NULL THEN 0 ELSE 1 END AS MASTER_JOIN_HIT,
       M.PRESC_NO,M.DISPENSARY,M.PRESC_SOURCE,M.FLAG,M.REFUND_FLAG,
       M.DISPENSING_DATETIME
FROM DRUG_USER.MED_TRACE_RECORD T
LEFT JOIN PHARMACY.DRUG_PRESC_MASTER M
  ON T.TRACE_BILLNO=TO_CHAR(M.PRESC_NO)
 AND T.PRESC_DATE=M.PRESC_DATE
 AND T.STORE_CODE=M.DISPENSARY
WHERE ((T.T_TRACE_CODE=:code_0 AND T.PRESC_DETAILID=:line_0)
    OR (T.T_TRACE_CODE=:code_1 AND T.PRESC_DETAILID=:line_1)
    OR (T.T_TRACE_CODE=:code_2 AND T.PRESC_DETAILID=:line_2))
  AND ROWNUM<=101
