-- r11 授权修正（ORA-01720 修复；DTR-R11-DDL-FIX-20261028 续，2026-10-28）
-- 现象：视图已建成，第 3 部分 GRANT SELECT ON PHARMACY.V_... TO BLYB_DRUGTRACE
--       报 ORA-01720（不存在底层表的授权选项）。
-- 原因：视图属主向外授权视图时，必须对基表持有 WITH GRANT OPTION 的对象权限；
--       第 0 部分授的是普通 SELECT。r10 的 MED_TRACE_RECORD 当年即带授权选项，
--       故本次仅三张新表缺（报错清单与之吻合：PHA_INP_DISPMASTER、
--       PHA_INP_REQUEST_DRUG、PHA_CLI_REQUEST_DRUG×2=两个退药视图引用）。
-- 执行：A 部分用 DRUG_USER 属主或 DBA（幂等，可重复执行）；
--       B 部分用 PHARMACY 属主或 DBA；C 部分用 BLYB_DRUGTRACE 验证。

-- ============ A 部分：补授权选项（DRUG_USER 属主 / DBA 执行） ============
GRANT SELECT ON DRUG_USER.PHA_INP_REQUEST_DRUG TO PHARMACY WITH GRANT OPTION;
GRANT SELECT ON DRUG_USER.PHA_INP_DISPMASTER   TO PHARMACY WITH GRANT OPTION;
GRANT SELECT ON DRUG_USER.PHA_CLI_REQUEST_DRUG TO PHARMACY WITH GRANT OPTION;
-- MED_TRACE_RECORD 若 r10 时已带授权选项可跳过；不确定就执行（幂等）：
GRANT SELECT ON DRUG_USER.MED_TRACE_RECORD     TO PHARMACY WITH GRANT OPTION;

-- ============ B 部分：重跑视图授权（PHARMACY 属主 / DBA 执行） ============
GRANT SELECT ON PHARMACY.V_DRUG_TRACE_BILL_INP    TO BLYB_DRUGTRACE;
GRANT SELECT ON PHARMACY.V_DRUG_TRACE_CODE_INP    TO BLYB_DRUGTRACE;
GRANT SELECT ON PHARMACY.V_DRUG_TRACE_RETURN      TO BLYB_DRUGTRACE;
GRANT SELECT ON PHARMACY.V_DRUG_TRACE_RETURN_CODE TO BLYB_DRUGTRACE;

