-- 在库基线（P0 固化，2026-11-15）
CREATE OR REPLACE FORCE VIEW ODS.V_INF_EX_LAB_ITEM AS
SELECT
  a.TEST_NO||c.PRINT_ORDER AS ID,
  a.TEST_NO AS EX_LAB_ID,
  c.REPORT_ITEM_CODE AS ITEM_CODE,
  c.REPORT_ITEM_NAME AS ITEM_NAME,
  CASE WHEN c.RESULT LIKE '阳性%' THEN 'P' WHEN c.RESULT LIKE '阴性%' THEN 'N' ELSE c.ABNORMAL_INDICATOR END AS SOURCE_EXAMINATION_RESULT_CODE,
  CASE WHEN (c.RESULT LIKE '阳性%' OR c.ABNORMAL_INDICATOR='P') THEN '阳性'
       WHEN (c.RESULT LIKE '阴性%' OR c.ABNORMAL_INDICATOR='N') THEN '阴性'
       WHEN c.ABNORMAL_INDICATOR='H' THEN '偏高' WHEN c.ABNORMAL_INDICATOR='L' THEN '偏低'
       WHEN c.ABNORMAL_INDICATOR='Q' THEN '弱阳性' WHEN c.ABNORMAL_INDICATOR='E' THEN '错误'
       WHEN c.ABNORMAL_INDICATOR='M' THEN '正常' WHEN c.ABNORMAL_INDICATOR='S' THEN '敏感'
       WHEN c.ABNORMAL_INDICATOR='R' THEN '耐药' END AS SOURCE_EXAMINATION_RESULT_NAME,
  CASE WHEN (c.RESULT LIKE '阳性%' OR c.ABNORMAL_INDICATOR='P') THEN '01'
       WHEN (c.RESULT LIKE '阴性%' OR c.ABNORMAL_INDICATOR='N') THEN '02'
       WHEN c.ABNORMAL_INDICATOR='H' THEN '12' WHEN c.ABNORMAL_INDICATOR='L' THEN '10'
       WHEN c.ABNORMAL_INDICATOR='Q' THEN '05' WHEN c.ABNORMAL_INDICATOR='S' THEN '15'
       WHEN c.ABNORMAL_INDICATOR='R' THEN '16' END AS EXAMINATION_RESULT_CODE,
  CASE WHEN (c.RESULT LIKE '阳性%' OR c.ABNORMAL_INDICATOR='P') THEN '阳性'
       WHEN (c.RESULT LIKE '阴性%' OR c.ABNORMAL_INDICATOR='N') THEN '阴性'
       WHEN c.ABNORMAL_INDICATOR='H' THEN 'H 高度耐药' WHEN c.ABNORMAL_INDICATOR='L' THEN 'L 低度耐药'
       WHEN c.ABNORMAL_INDICATOR='Q' THEN '弱阳性' WHEN c.ABNORMAL_INDICATOR='E' THEN '未检出'
       WHEN c.ABNORMAL_INDICATOR='M' THEN '检出' WHEN c.ABNORMAL_INDICATOR='S' THEN '敏感'
       WHEN c.ABNORMAL_INDICATOR='R' THEN '耐药' END AS EXAMINATION_RESULT_NAME,
  c.RESULT AS EXAMINATION_QUANTIFICATION,
  c.UNITS AS EXAMINATION_QUANTIFICA_UNIT,
  CASE WHEN (c.RESULT LIKE '阳性%' OR c.ABNORMAL_INDICATOR='P') THEN '0'
       WHEN (c.RESULT LIKE '阴性%' OR c.ABNORMAL_INDICATOR='N') THEN '0'
       ELSE SUBSTRB(REGEXP_SUBSTR(c.PRINT_CONTEXT,'^[^-]+'),1,20) END AS EXAMINATION_QUANTIFICA_LOWER,  -- 【v1.1】加20位截断（平台04"下限长度不超过20位"；CRBSB原版UPPER有截LOWER漏）
  CASE WHEN (c.RESULT LIKE '阳性%' OR c.ABNORMAL_INDICATOR='P') THEN '0'
       WHEN (c.RESULT LIKE '阴性%' OR c.ABNORMAL_INDICATOR='N') THEN '0'
       ELSE SUBSTRB(REGEXP_SUBSTR(c.PRINT_CONTEXT,'[^-]+$',1,1),1,20) END AS EXAMINATION_QUANTIFICA_UPPER,
  CASE WHEN (c.RESULT LIKE '阳性%' OR c.ABNORMAL_INDICATOR='P') THEN '0'
       WHEN (c.RESULT LIKE '阴性%' OR c.ABNORMAL_INDICATOR='N') THEN '0'
       WHEN c.ABNORMAL_INDICATOR='H' THEN '2' WHEN c.ABNORMAL_INDICATOR='L' THEN '1'
       WHEN c.ABNORMAL_INDICATOR='Q' THEN '0' WHEN c.ABNORMAL_INDICATOR='E' THEN '0'
       WHEN c.ABNORMAL_INDICATOR='M' THEN '0' WHEN c.ABNORMAL_INDICATOR='S' THEN '2'
       WHEN c.ABNORMAL_INDICATOR='R' THEN '0' ELSE '0' END AS EXAMINATION_QUANTIFICATION_RI,
  (CASE WHEN REGEXP_LIKE(a.TRANSCRIPTIONIST,'[0-9]') THEN a.TRANSCRIPTIONIST
        ELSE (SELECT MAX(y.EMP_NO) FROM HIS.STAFF_DICT y WHERE y.NAME=a.TRANSCRIPTIONIST) END) AS OPERATOR_ID,
  NVL(a.EXECUTE_DATE,a.REQUESTED_DATE_TIME) AS OPERATION_TIME
FROM HIS.LAB_TEST_MASTER a
JOIN HIS.LAB_TEST_ITEMS b ON a.TEST_NO=b.TEST_NO
JOIN HIS.LAB_RESULT c ON a.TEST_NO=c.TEST_NO AND b.ITEM_NO=c.ITEM_NO
JOIN HIS.PAT_MASTER_INDEX pmi ON pmi.PATIENT_ID=a.PATIENT_ID
WHERE a.RESULTS_RPT_DATE_TIME IS NOT NULL
  AND a.RESULT_STATUS='4'
  AND c.REPORT_ID IS NOT NULL
  AND a.VISIT_ID<>'0'
  AND a.RESULTS_RPT_DATE_TIME>=DATE'2026-01-01'
  AND EXISTS (SELECT 1 FROM ODS.M_INF_FXHIS_ACTIVITY act
              WHERE TRIM(act.PATIENT_ID)=TRIM(a.PATIENT_ID)
                AND TRIM(act.SERIAL_NUMBER)=TRIM(pmi.INP_NO||a.VISIT_ID))

UNION ALL
