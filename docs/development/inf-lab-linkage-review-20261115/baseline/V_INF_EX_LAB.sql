-- 在库基线（P0 固化，2026-11-15）
CREATE OR REPLACE FORCE VIEW ODS.V_INF_EX_LAB AS
SELECT
  a.TEST_NO AS ID,
  NVL(a.PATIENT_ID,'-') AS PATIENT_ID,
  '6' AS ACTIVITY_TYPE_CODE,
  '住院' AS ACTIVITY_TYPE_NAME,
  pmi.INP_NO || a.VISIT_ID AS SERIAL_NUMBER,
  pmi.NAME AS PATIENT_NAME,
  '01' AS ID_CARD_TYPE_CODE,
  '居民身份证' AS ID_CARD_TYPE_NAME,
  NVL(pmi.ID_NO,'-') AS ID_CARD,
  pv.DISCHARGE_WARD_CODE AS WARD_NAME,
  '' AS WARD_NO,
  TO_CHAR(pv.DISCHARGE_BED_NO) AS BED_NO,
  NVL(a.TEST_NO,'-') AS APPLICATION_FORM_NO,
  (SELECT MAX(dd.INFECT_DEPT_CODE) FROM HIS.INFECT_DEPT_DICT dd WHERE dd.HIS_DEPT_CODE=a.ORDERING_DEPT) AS APPLY_DEPT_CODE,
  (SELECT MAX(dd.INFECT_DEPT_NAME) FROM HIS.INFECT_DEPT_DICT dd WHERE dd.HIS_DEPT_CODE=a.ORDERING_DEPT) AS APPLY_DEPT_NAME,
  '370104000' AS APPLY_ORG_CODE,
  '山东省第二人民医院' AS APPLY_ORG_NAME,
  a.ORDERING_PROVIDER AS APPLY_PHYSICIAN_ID,
  NVL((SELECT dd.INFECT_SPECIMEN_CODE FROM HIS.LIS_SPECIMEN_DICT dd WHERE dd.HIS_SPECIMEN_NAME=a.SPECIMEN),'99') AS SPECIMEN_CATEGORY_CODE,
  NVL((SELECT dd.INFECT_SPECIMEN_NAME FROM HIS.LIS_SPECIMEN_DICT dd WHERE dd.HIS_SPECIMEN_NAME=a.SPECIMEN),'其他') AS SPECIMEN_CATEGORY_NAME,
  NVL(a.TEST_NO,'-') AS SPECIMEN_NO,
  TO_CHAR(a.SPCM_SAMPLE_DATE_TIME,'YYYY-MM-DD HH24:MI:SS') AS SPECIMEN_SAMPLING_DATE,
  TO_CHAR(a.SPCM_RECEIVED_DATE_TIME,'YYYY-MM-DD HH24:MI:SS') AS SPECIMEN_RECEIVING_DATE,
  (CASE WHEN REGEXP_LIKE(a.TRANSCRIPTIONIST,'[0-9]') THEN a.TRANSCRIPTIONIST
        ELSE (SELECT MAX(y.EMP_NO) FROM HIS.STAFF_DICT y WHERE y.NAME=a.TRANSCRIPTIONIST) END) AS EXAMINATION_PHYSICIAN_ID,
  TO_CHAR(a.EXECUTE_DATE,'YYYY-MM-DD HH24:MI:SS') AS EXAMINATION_DATE,
  NVL(a.RCPT_NO,(SELECT MAX(lr.Report_Id) FROM HIS.LAB_RESULT lr WHERE lr.TEST_NO=a.TEST_NO)) AS EXAMINATION_REPORT_NO,
  '' AS EXAMINATION_OBJECTIVE_DESC,
  '' AS EEXAMINATION_SUBJECTIVE_DESC,
  '' AS EXAMINATION_NOTES,
  TO_CHAR(a.RESULTS_RPT_DATE_TIME,'YYYY-MM-DD HH24:MI:SS') AS EXAMINATION_REPORT_DATE,
  (CASE WHEN REGEXP_LIKE(a.TRANSCRIPTIONIST,'[0-9]') THEN a.TRANSCRIPTIONIST
        ELSE (SELECT MAX(y.EMP_NO) FROM HIS.STAFF_DICT y WHERE y.NAME=a.TRANSCRIPTIONIST) END) AS EXAMINATION_REPORT_ID,
  '370104000' AS ORG_CODE,
  '山东省第二人民医院' AS ORG_NAME,
  (SELECT MAX(dd.INFECT_DEPT_CODE) FROM HIS.INFECT_DEPT_DICT dd WHERE dd.HIS_DEPT_CODE=a.PERFORMED_BY) AS DEPT_CODE,
  (SELECT MAX(dd.INFECT_DEPT_NAME) FROM HIS.INFECT_DEPT_DICT dd WHERE dd.HIS_DEPT_CODE=a.PERFORMED_BY) AS DEPT_NAME,
  (CASE WHEN REGEXP_LIKE(a.TRANSCRIPTIONIST,'[0-9]') THEN a.TRANSCRIPTIONIST
        ELSE (SELECT MAX(y.EMP_NO) FROM HIS.STAFF_DICT y WHERE y.NAME=a.TRANSCRIPTIONIST) END) AS OPERATOR_ID,
  NVL(a.EXECUTE_DATE,a.REQUESTED_DATE_TIME) AS OPERATION_TIME
FROM HIS.LAB_TEST_MASTER a
JOIN HIS.PAT_MASTER_INDEX pmi ON pmi.PATIENT_ID = a.PATIENT_ID
JOIN HIS.PAT_VISIT pv ON pv.PATIENT_ID = a.PATIENT_ID AND pv.VISIT_ID = a.VISIT_ID
WHERE a.RESULTS_RPT_DATE_TIME IS NOT NULL
  AND a.RESULT_STATUS = '4'
  AND a.VISIT_ID <> '0'
  AND a.RESULTS_RPT_DATE_TIME >= DATE'2026-01-01'
  AND EXISTS (SELECT 1 FROM ODS.M_INF_FXHIS_ACTIVITY act
              WHERE TRIM(act.PATIENT_ID) = TRIM(a.PATIENT_ID)
                AND TRIM(act.SERIAL_NUMBER) = TRIM(pmi.INP_NO || a.VISIT_ID))

UNION ALL
