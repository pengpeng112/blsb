-- 仅核实三表主键/唯一约束，不凭PK索引名称猜测唯一性。
SELECT C.TABLE_NAME,C.CONSTRAINT_NAME,C.CONSTRAINT_TYPE,CC.COLUMN_NAME,CC.POSITION,C.STATUS
FROM ALL_CONSTRAINTS C JOIN ALL_CONS_COLUMNS CC
ON C.OWNER=CC.OWNER AND C.CONSTRAINT_NAME=CC.CONSTRAINT_NAME
WHERE C.OWNER='PHARMACY'
AND C.TABLE_NAME IN ('DRUG_PRESC_TRACE_CODE','DRUG_PRESC_MASTER','DRUG_PRESC_DETAIL')
AND C.CONSTRAINT_TYPE IN ('P','U') AND ROWNUM<=30
ORDER BY C.TABLE_NAME,C.CONSTRAINT_NAME,CC.POSITION
