-- 核查用户原SQL未限定owner的对象是否存在同名表/同义词，避免误选来源。
SELECT OWNER,OBJECT_NAME AS NAME,OBJECT_TYPE AS KIND,OWNER AS TARGET_OWNER,OBJECT_NAME AS TARGET_NAME
FROM ALL_OBJECTS WHERE OBJECT_NAME='MED_TRACE_RECORD' AND OBJECT_TYPE IN ('TABLE','VIEW')
UNION ALL
SELECT OWNER,SYNONYM_NAME AS NAME,'SYNONYM' AS KIND,TABLE_OWNER AS TARGET_OWNER,TABLE_NAME AS TARGET_NAME
FROM ALL_SYNONYMS WHERE SYNONYM_NAME='MED_TRACE_RECORD'
