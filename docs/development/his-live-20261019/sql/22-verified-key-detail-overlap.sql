-- 样本已确认TRACE_BILLNO、完整PRESC_DATE和药房均可相等；现三者一起限定10张处方，最多100行。
-- PRESC_DETAILID的两种候选关联只做计数核验，全部受处方复合键收窄；不输出明细标识。
SELECT HEADER_SOURCE,HEADER_FLAG,SPLIT_FLAG,IS_DELETED,COUNT(*) AS SAMPLE_ROWS,
COUNT(DISTINCT TRACE_BILLNO) AS DISTINCT_BILL_NUMBERS,
SUM(CASE WHEN ITEM_NO_MATCHES=1 THEN 1 ELSE 0 END) AS UNIQUE_ITEM_NO_MATCH,
SUM(CASE WHEN COST_ID_MATCHES=1 THEN 1 ELSE 0 END) AS UNIQUE_COST_ID_MATCH,
SUM(CASE WHEN DRUG_CODE_MATCHES=1 THEN 1 ELSE 0 END) AS UNIQUE_DRUG_CODE_MATCH,
SUM(CASE WHEN DRUG_CODE_MATCHES>1 THEN 1 ELSE 0 END) AS AMBIGUOUS_DRUG_CODE_MATCH,
SUM(CASE WHEN REGEXP_LIKE(PRESC_DETAILID,'^[0-9]+$') THEN 1 ELSE 0 END) AS NUMERIC_DETAIL_ID,
SUM(CASE WHEN LENGTH(T_TRACE_CODE)=20 AND REGEXP_LIKE(T_TRACE_CODE,'^[0-9]+$') THEN 1 ELSE 0 END) AS CODE_20_DIGITS,
SUM(CASE WHEN TRACES_SUM>1 THEN 1 ELSE 0 END) AS COUNT_MORE_THAN_ONE,
COUNT(MODIFY_TIME) AS HAS_MODIFY_TIME,
SUM(CASE WHEN CREATE_TIME<TO_DATE('2026-10-11','yyyy-mm-dd') OR CREATE_TIME>=TO_DATE('2026-10-12','yyyy-mm-dd') THEN 1 ELSE 0 END) AS SCAN_TIME_OUTSIDE_HEADER_DAY
FROM (
SELECT T.TRACE_BILLNO,T.PRESC_DETAILID,T.T_TRACE_CODE,T.SPLIT_FLAG,T.IS_DELETED,T.TRACES_SUM,T.MODIFY_TIME,T.CREATE_TIME,
M.PRESC_SOURCE AS HEADER_SOURCE,M.FLAG AS HEADER_FLAG,
(SELECT COUNT(*) FROM PHARMACY.DRUG_PRESC_DETAIL D
WHERE D.PRESC_DATE=M.PRESC_DATE AND D.PRESC_NO=M.PRESC_NO
AND TO_CHAR(D.ITEM_NO)=T.PRESC_DETAILID AND ROWNUM<=2) AS ITEM_NO_MATCHES,
(SELECT COUNT(*) FROM PHARMACY.DRUG_PRESC_DETAIL D
WHERE D.PRESC_DATE=M.PRESC_DATE AND D.PRESC_NO=M.PRESC_NO
AND TO_CHAR(D.ORDER_ITEM_COST_ID)=T.PRESC_DETAILID AND ROWNUM<=2) AS COST_ID_MATCHES,
(SELECT COUNT(*) FROM PHARMACY.DRUG_PRESC_DETAIL D
WHERE D.PRESC_DATE=M.PRESC_DATE AND D.PRESC_NO=M.PRESC_NO
AND D.DRUG_CODE=T.DRUG_ID AND ROWNUM<=2) AS DRUG_CODE_MATCHES
FROM (
SELECT PRESC_DATE,PRESC_NO,DISPENSARY,PRESC_SOURCE,FLAG FROM PHARMACY.DRUG_PRESC_MASTER
WHERE DISPENSING_DATETIME>=TO_DATE('2026-10-11','yyyy-mm-dd')
AND DISPENSING_DATETIME<TO_DATE('2026-10-12','yyyy-mm-dd') AND ROWNUM<=10
) M JOIN DRUG_USER.MED_TRACE_RECORD T
ON T.TRACE_BILLNO=TO_CHAR(M.PRESC_NO) AND T.PRESC_DATE=M.PRESC_DATE AND T.STORE_CODE=M.DISPENSARY
WHERE T.IN_OUT_TYPE='OUT' AND ROWNUM<=100
)
GROUP BY HEADER_SOURCE,HEADER_FLAG,SPLIT_FLAG,IS_DELETED
