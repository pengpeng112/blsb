-- 23的脱敏结构提示时间戳_处方号_序号；此处只验证候选重组键，不先解析/截断原ID。
-- 处方日期/号已通过主键收窄，不扫描全明细；只输出匹配数与数量/单位可用性。
SELECT SPLIT_FLAG,COUNT(*) AS SAMPLE_ROWS,
SUM(CASE WHEN DETAIL_MATCHES=1 THEN 1 ELSE 0 END) AS UNIQUE_COMPOSITE_DETAIL_MATCH,
SUM(CASE WHEN DETAIL_MATCHES>1 THEN 1 ELSE 0 END) AS AMBIGUOUS_DETAIL_MATCH,
SUM(CASE WHEN HAS_QUANTITY=1 THEN 1 ELSE 0 END) AS MATCH_HAS_QUANTITY,
SUM(CASE WHEN HAS_UNITS=1 THEN 1 ELSE 0 END) AS MATCH_HAS_UNITS
FROM (
SELECT T.SPLIT_FLAG,
(SELECT COUNT(*) FROM PHARMACY.DRUG_PRESC_DETAIL D
WHERE D.PRESC_DATE=M.PRESC_DATE AND D.PRESC_NO=M.PRESC_NO
AND TO_CHAR(D.PRESC_DATE,'YYYYMMDDHH24MISS')||'_'||TO_CHAR(D.PRESC_NO)||'_'||TO_CHAR(D.ITEM_NO)=T.PRESC_DETAILID
AND ROWNUM<=2) AS DETAIL_MATCHES,
(SELECT COUNT(D.QUANTITY) FROM PHARMACY.DRUG_PRESC_DETAIL D
WHERE D.PRESC_DATE=M.PRESC_DATE AND D.PRESC_NO=M.PRESC_NO
AND TO_CHAR(D.PRESC_DATE,'YYYYMMDDHH24MISS')||'_'||TO_CHAR(D.PRESC_NO)||'_'||TO_CHAR(D.ITEM_NO)=T.PRESC_DETAILID
AND ROWNUM<=2) AS HAS_QUANTITY,
(SELECT COUNT(D.PACKAGE_UNITS) FROM PHARMACY.DRUG_PRESC_DETAIL D
WHERE D.PRESC_DATE=M.PRESC_DATE AND D.PRESC_NO=M.PRESC_NO
AND TO_CHAR(D.PRESC_DATE,'YYYYMMDDHH24MISS')||'_'||TO_CHAR(D.PRESC_NO)||'_'||TO_CHAR(D.ITEM_NO)=T.PRESC_DETAILID
AND ROWNUM<=2) AS HAS_UNITS
FROM (
SELECT PRESC_DATE,PRESC_NO,DISPENSARY FROM PHARMACY.DRUG_PRESC_MASTER
WHERE DISPENSING_DATETIME>=TO_DATE('2026-10-11','yyyy-mm-dd')
AND DISPENSING_DATETIME<TO_DATE('2026-10-12','yyyy-mm-dd') AND ROWNUM<=10
) M JOIN DRUG_USER.MED_TRACE_RECORD T
ON T.TRACE_BILLNO=TO_CHAR(M.PRESC_NO) AND T.PRESC_DATE=M.PRESC_DATE AND T.STORE_CODE=M.DISPENSARY
WHERE T.IN_OUT_TYPE='OUT' AND ROWNUM<=100
)
GROUP BY SPLIT_FLAG
