-- 已核实PRESC_DATE为索引首列；用户历史区间内2026-10-11一天，最多50条追溯明细。
-- 与MED表仅按已索引追溯码做候选重叠核验；不将相同码自动认作同一业务/单据。
-- 每个码最多探查21条匹配，避免异常重复扩大查询；只输出总计，不输出患者、处方号或码。
SELECT COUNT(*) AS SAMPLE_ROWS,MIN(LENGTH(TRACE_CODE)) AS MIN_CODE_LENGTH,
MAX(LENGTH(TRACE_CODE)) AS MAX_CODE_LENGTH,
SUM(CASE WHEN REGEXP_LIKE(TRACE_CODE,'^[0-9]+$') THEN 1 ELSE 0 END) AS DIGITS_ONLY,
COUNT(QUANTITY) AS HAS_QUANTITY,COUNT(PACKAGE_UNITS) AS HAS_UNITS,
MIN(QUANTITY) AS MIN_QUANTITY,MAX(QUANTITY) AS MAX_QUANTITY,
SUM(CASE WHEN HEADER_MATCHES=1 THEN 1 ELSE 0 END) AS UNIQUE_HEADER,
SUM(CASE WHEN HEADER_MATCHES=0 THEN 1 ELSE 0 END) AS NO_HEADER,
SUM(CASE WHEN MED_MATCHES>0 THEN 1 ELSE 0 END) AS CODE_FOUND_IN_MED,
SUM(CASE WHEN MED_OUT_MATCHES>0 THEN 1 ELSE 0 END) AS CODE_FOUND_IN_MED_OUT,
SUM(CASE WHEN MED_OUT_MATCHES>1 THEN 1 ELSE 0 END) AS MULTIPLE_MED_OUT,
COUNT(ENTER_DATE) AS HAS_ENTER_DATE
FROM (
SELECT S.TRACE_CODE,S.QUANTITY,S.PACKAGE_UNITS,S.ENTER_DATE,
(SELECT COUNT(*) FROM PHARMACY.DRUG_PRESC_MASTER M
WHERE M.PRESC_DATE=S.PRESC_DATE AND M.PRESC_NO=S.PRESC_NO AND ROWNUM<=2) AS HEADER_MATCHES,
(SELECT COUNT(*) FROM DRUG_USER.MED_TRACE_RECORD T
WHERE T.T_TRACE_CODE=S.TRACE_CODE AND ROWNUM<=21) AS MED_MATCHES,
(SELECT COUNT(*) FROM DRUG_USER.MED_TRACE_RECORD T
WHERE T.T_TRACE_CODE=S.TRACE_CODE AND T.IN_OUT_TYPE='OUT' AND ROWNUM<=21) AS MED_OUT_MATCHES
FROM (
SELECT PRESC_DATE,PRESC_NO,TRACE_CODE,QUANTITY,PACKAGE_UNITS,ENTER_DATE
FROM PHARMACY.DRUG_PRESC_TRACE_CODE
WHERE PRESC_DATE>=TO_DATE('2026-10-11','yyyy-mm-dd')
AND PRESC_DATE<TO_DATE('2026-10-12','yyyy-mm-dd') AND ROWNUM<=50
) S
)
