-- 使用已核实的发药时间索引，2026-10-11最多20张已记录发药时间的处方。
-- TRACE_BILLNO注释带问号，以下只检验候选数值处方号关联，不能据此批准业务关联。
-- 每张处方最多探查21条匹配，全部只返回汇总，不输出真实处方号。
SELECT COUNT(*) AS SAMPLE_PRESCRIPTIONS,COUNT(DISPENSARY) AS HAS_DISPENSARY,
SUM(CASE WHEN MED_BILL_MATCHES>0 THEN 1 ELSE 0 END) AS MATCHES_BILL_NUMBER,
SUM(CASE WHEN MED_OUT_MATCHES>0 THEN 1 ELSE 0 END) AS MATCHES_OUT_BILL,
SUM(CASE WHEN MED_OUT_MATCHES>=21 THEN 1 ELSE 0 END) AS OUT_MATCH_CAP_REACHED
FROM (
SELECT M.DISPENSARY,
(SELECT COUNT(*) FROM DRUG_USER.MED_TRACE_RECORD T
WHERE T.TRACE_BILLNO=TO_CHAR(M.PRESC_NO) AND ROWNUM<=21) AS MED_BILL_MATCHES,
(SELECT COUNT(*) FROM DRUG_USER.MED_TRACE_RECORD T
WHERE T.TRACE_BILLNO=TO_CHAR(M.PRESC_NO) AND T.IN_OUT_TYPE='OUT' AND ROWNUM<=21) AS MED_OUT_MATCHES
FROM (
SELECT PRESC_DATE,PRESC_NO,DISPENSARY FROM PHARMACY.DRUG_PRESC_MASTER
WHERE DISPENSING_DATETIME>=TO_DATE('2026-10-11','yyyy-mm-dd')
AND DISPENSING_DATETIME<TO_DATE('2026-10-12','yyyy-mm-dd') AND ROWNUM<=20
) M
)
