-- 同一主键索引取最后100个键，只返回汇总，仍不是按时间排序。
-- 主键排序取样，不代表时间分布、历史区间或完整值域；不输出真实键/码/单号。
SELECT IN_OUT_TYPE,KIND_TYPE,IS_DELETED,SPLIT_FLAG,
COUNT(*) AS SAMPLE_ROWS,COUNT(TRACE_BILLNO) AS HAS_BILL_NO,
COUNT(PRESC_DETAILID) AS HAS_PRESC_DETAIL,
COUNT(F_TRACE_CODE) AS HAS_F_CODE,COUNT(S_TRACE_CODE) AS HAS_S_CODE,
COUNT(T_TRACE_CODE) AS HAS_T_CODE,
MIN(LENGTH(T_TRACE_CODE)) AS MIN_T_LENGTH,MAX(LENGTH(T_TRACE_CODE)) AS MAX_T_LENGTH,
SUM(CASE WHEN INSTR(T_TRACE_CODE,',')>0 THEN 1 ELSE 0 END) AS T_HAS_COMMA,
SUM(CASE WHEN INSTR(PRESC_DETAILID,',')>0 THEN 1 ELSE 0 END) AS DETAIL_HAS_COMMA,
SUM(CASE WHEN REGEXP_LIKE(T_TRACE_CODE,'^[0-9]+$') THEN 1 ELSE 0 END) AS T_DIGITS_ONLY,
COUNT(MODIFY_TIME) AS HAS_MODIFY_TIME,COUNT(DELETE_TIME) AS HAS_DELETE_TIME,
MIN(TRACES_SUM) AS MIN_TRACES_SUM,MAX(TRACES_SUM) AS MAX_TRACES_SUM,
MIN(CREATE_TIME) AS EARLIEST_SAMPLE_TIME,MAX(CREATE_TIME) AS LATEST_SAMPLE_TIME
FROM (
SELECT TRACE_BILLNO,PRESC_DETAILID,F_TRACE_CODE,S_TRACE_CODE,T_TRACE_CODE,
IN_OUT_TYPE,KIND_TYPE,IS_DELETED,SPLIT_FLAG,MODIFY_TIME,DELETE_TIME,TRACES_SUM,CREATE_TIME
FROM DRUG_USER.MED_TRACE_RECORD
WHERE RECORD_ID IN (
SELECT RECORD_ID FROM (
SELECT RECORD_ID FROM DRUG_USER.MED_TRACE_RECORD ORDER BY RECORD_ID DESC
) WHERE ROWNUM<=100
) AND ROWNUM<=100
)
GROUP BY IN_OUT_TYPE,KIND_TYPE,IS_DELETED,SPLIT_FLAG
