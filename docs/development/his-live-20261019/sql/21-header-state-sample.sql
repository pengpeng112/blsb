-- 发药日期索引下最多100张处方，状态只观测原值，不依据注释直接启用生产过滤。
SELECT FLAG,PRESC_SOURCE,REFUND_FLAG,TRACE_STATUS,COUNT(*) AS SAMPLE_BILLS,
COUNT(DISPENSARY) AS HAS_DISPENSARY
FROM (
SELECT FLAG,PRESC_SOURCE,REFUND_FLAG,TRACE_STATUS,DISPENSARY
FROM PHARMACY.DRUG_PRESC_MASTER
WHERE DISPENSING_DATETIME>=TO_DATE('2026-10-11','yyyy-mm-dd')
AND DISPENSING_DATETIME<TO_DATE('2026-10-12','yyyy-mm-dd') AND ROWNUM<=100
)
GROUP BY FLAG,PRESC_SOURCE,REFUND_FLAG,TRACE_STATUS
