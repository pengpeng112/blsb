-- 日期索引取10张处方，业务单号索引关联MED出库记录；额外限定扫码时间当天，最多100行。
-- 等值候选关联仍需检查完整处方日期与药房，不直接批准生产JOIN。
SELECT IN_OUT_TYPE,KIND_TYPE,IS_DELETED,SPLIT_FLAG,
COUNT(*) AS SAMPLE_ROWS,COUNT(DISTINCT TRACE_BILLNO) AS DISTINCT_BILLS,
COUNT(PRESC_DETAILID) AS HAS_PRESC_DETAIL,
SUM(CASE WHEN INSTR(PRESC_DETAILID,',')>0 THEN 1 ELSE 0 END) AS DETAIL_HAS_COMMA,
COUNT(T_TRACE_CODE) AS HAS_T_CODE,MIN(LENGTH(T_TRACE_CODE)) AS MIN_T_LENGTH,
MAX(LENGTH(T_TRACE_CODE)) AS MAX_T_LENGTH,
SUM(CASE WHEN REGEXP_LIKE(T_TRACE_CODE,'^[0-9]+$') THEN 1 ELSE 0 END) AS T_DIGITS_ONLY,
COUNT(F_TRACE_CODE) AS HAS_F_CODE,COUNT(S_TRACE_CODE) AS HAS_S_CODE,
COUNT(MODIFY_TIME) AS HAS_MODIFY_TIME,COUNT(DELETE_TIME) AS HAS_DELETE_TIME,
MIN(TRACES_SUM) AS MIN_TRACES_SUM,MAX(TRACES_SUM) AS MAX_TRACES_SUM,
SUM(CASE WHEN PRESC_DATE=HEADER_PRESC_DATE THEN 1 ELSE 0 END) AS EXACT_PRESC_DATE_MATCH,
SUM(CASE WHEN STORE_CODE=HEADER_DISPENSARY THEN 1 ELSE 0 END) AS PHARMACY_MATCH,
MIN(CREATE_TIME) AS FIRST_SCAN_TIME,MAX(CREATE_TIME) AS LAST_SCAN_TIME
FROM (
SELECT T.TRACE_BILLNO,T.PRESC_DETAILID,T.T_TRACE_CODE,T.F_TRACE_CODE,T.S_TRACE_CODE,
T.IN_OUT_TYPE,T.KIND_TYPE,T.IS_DELETED,T.SPLIT_FLAG,T.MODIFY_TIME,T.DELETE_TIME,
T.TRACES_SUM,T.CREATE_TIME,T.PRESC_DATE,T.STORE_CODE,
M.PRESC_DATE AS HEADER_PRESC_DATE,M.DISPENSARY AS HEADER_DISPENSARY
FROM (
SELECT PRESC_DATE,PRESC_NO,DISPENSARY FROM PHARMACY.DRUG_PRESC_MASTER
WHERE DISPENSING_DATETIME>=TO_DATE('2026-10-11','yyyy-mm-dd')
AND DISPENSING_DATETIME<TO_DATE('2026-10-12','yyyy-mm-dd') AND ROWNUM<=10
) M JOIN DRUG_USER.MED_TRACE_RECORD T ON T.TRACE_BILLNO=TO_CHAR(M.PRESC_NO)
WHERE T.IN_OUT_TYPE='OUT'
AND T.CREATE_TIME>=TO_DATE('2026-10-11','yyyy-mm-dd')
AND T.CREATE_TIME<TO_DATE('2026-10-12','yyyy-mm-dd') AND ROWNUM<=100
)
GROUP BY IN_OUT_TYPE,KIND_TYPE,IS_DELETED,SPLIT_FLAG
