-- 追溯表主键/唯一约束，只读元数据，最多30行；无业务明细。
SELECT C.CONSTRAINT_NAME,C.CONSTRAINT_TYPE,CC.COLUMN_NAME,CC.POSITION,C.STATUS
FROM ALL_CONSTRAINTS C JOIN ALL_CONS_COLUMNS CC
ON C.OWNER=CC.OWNER AND C.CONSTRAINT_NAME=CC.CONSTRAINT_NAME
WHERE C.OWNER='DRUG_USER' AND C.TABLE_NAME='MED_TRACE_RECORD'
AND C.CONSTRAINT_TYPE IN ('P','U') AND ROWNUM<=30
ORDER BY C.CONSTRAINT_NAME,CC.POSITION
