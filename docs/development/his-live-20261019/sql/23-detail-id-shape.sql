-- 只输出明细ID的脱敏格式：所有字母数字替换为X，保留分隔符，不返回实际标识。
SELECT REGEXP_REPLACE(PRESC_DETAILID,'[[:alnum:]]','X') AS MASKED_ID_SHAPE,
LENGTH(PRESC_DETAILID) AS ID_LENGTH,COUNT(*) AS SAMPLE_ROWS
FROM (
SELECT T.PRESC_DETAILID FROM (
SELECT PRESC_DATE,PRESC_NO,DISPENSARY FROM PHARMACY.DRUG_PRESC_MASTER
WHERE DISPENSING_DATETIME>=TO_DATE('2026-10-11','yyyy-mm-dd')
AND DISPENSING_DATETIME<TO_DATE('2026-10-12','yyyy-mm-dd') AND ROWNUM<=10
) M JOIN DRUG_USER.MED_TRACE_RECORD T
ON T.TRACE_BILLNO=TO_CHAR(M.PRESC_NO) AND T.PRESC_DATE=M.PRESC_DATE AND T.STORE_CODE=M.DISPENSARY
WHERE T.IN_OUT_TYPE='OUT' AND ROWNUM<=100
)
GROUP BY REGEXP_REPLACE(PRESC_DETAILID,'[[:alnum:]]','X'),LENGTH(PRESC_DETAILID)
