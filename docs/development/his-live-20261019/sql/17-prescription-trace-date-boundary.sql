-- 已核实PRESC_DATE为非空主键首列；分别取索引首尾1个日期，不读全表明细。
SELECT
(SELECT PRESC_DATE FROM (SELECT PRESC_DATE FROM PHARMACY.DRUG_PRESC_TRACE_CODE
ORDER BY PRESC_DATE) WHERE ROWNUM<=1) AS FIRST_TRACE_DATE,
(SELECT PRESC_DATE FROM (SELECT PRESC_DATE FROM PHARMACY.DRUG_PRESC_TRACE_CODE
ORDER BY PRESC_DATE DESC) WHERE ROWNUM<=1) AS LAST_TRACE_DATE
FROM DUAL
