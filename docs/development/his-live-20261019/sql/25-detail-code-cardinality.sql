-- 每条处方明细可能对应多个扫码记录；只输出度数分布，不输出真实明细ID或码。
SELECT CODE_RECORDS_PER_DETAIL,COUNT(*) AS DETAIL_GROUPS,
SUM(CASE WHEN MAX_TRACE_COUNTER>1 THEN 1 ELSE 0 END) AS GROUPS_TRACE_COUNTER_OVER_ONE
FROM (
SELECT PRESC_DETAILID,COUNT(*) AS CODE_RECORDS_PER_DETAIL,MAX(TRACES_SUM) AS MAX_TRACE_COUNTER
FROM (
SELECT T.PRESC_DETAILID,T.TRACES_SUM FROM (
SELECT PRESC_DATE,PRESC_NO,DISPENSARY FROM PHARMACY.DRUG_PRESC_MASTER
WHERE DISPENSING_DATETIME>=TO_DATE('2026-10-11','yyyy-mm-dd')
AND DISPENSING_DATETIME<TO_DATE('2026-10-12','yyyy-mm-dd') AND ROWNUM<=10
) M JOIN DRUG_USER.MED_TRACE_RECORD T
ON T.TRACE_BILLNO=TO_CHAR(M.PRESC_NO) AND T.PRESC_DATE=M.PRESC_DATE AND T.STORE_CODE=M.DISPENSARY
WHERE T.IN_OUT_TYPE='OUT' AND ROWNUM<=100
)
GROUP BY PRESC_DETAILID
)
GROUP BY CODE_RECORDS_PER_DETAIL
