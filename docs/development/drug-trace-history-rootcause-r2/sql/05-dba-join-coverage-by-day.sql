-- 未执行：Q04 按天JOIN覆盖统计（DBA/已批准审计身份执行）。
-- 目的：量化“源有但当前视图看不见”的规模——按主单 PRESC_DATE 逐日统计
-- 扫码记录三键JOIN命中率，区分 IN_OUT_TYPE='OUT' 与非OUT、JOIN未命中明细。
-- 索引依据：DRUG_PRESC_MASTER(PRESC_DATE,PRESC_NO) 主键索引（2026-10-19快照）；
-- 本查询按单日执行，绑定 :day_begin/:day_end 为同一天 00:00:00 与次日 00:00:00。
-- 注意：这是按处方日期的覆盖统计，不是旧SQL的扫码CREATE_TIME口径；
--      CREATE_TIME 无索引（快照），未经DBA确认新索引前不得对3个月做CREATE_TIME范围扫描。
-- 每天单独执行一次；返回行数小（聚合），不导出患者字段。
SELECT M.PRESC_DATE AS PRESC_DAY,
       T.IN_OUT_TYPE AS IN_OUT,
       CASE WHEN M.PRESC_NO IS NULL THEN 'JOIN_MISS' ELSE 'JOIN_HIT' END AS JOIN_STATE,
       T.IS_DELETED AS DELETED_RAW,
       COUNT(*) AS RECORD_ROWS,
       COUNT(DISTINCT T.RECORD_ID) AS DISTINCT_RECORDS,
       COUNT(DISTINCT T.PRESC_DETAILID) AS DISTINCT_LINE_IDS
FROM DRUG_USER.MED_TRACE_RECORD T
LEFT JOIN PHARMACY.DRUG_PRESC_MASTER M
  ON T.TRACE_BILLNO=TO_CHAR(M.PRESC_NO)
 AND T.PRESC_DATE=M.PRESC_DATE
 AND T.STORE_CODE=M.DISPENSARY
WHERE T.PRESC_DATE>=:day_begin AND T.PRESC_DATE<:day_end
  AND ROWNUM<=100000
GROUP BY M.PRESC_DATE,T.IN_OUT_TYPE,
         CASE WHEN M.PRESC_NO IS NULL THEN 'JOIN_MISS' ELSE 'JOIN_HIT' END,
         T.IS_DELETED
