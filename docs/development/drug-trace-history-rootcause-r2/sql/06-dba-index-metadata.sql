-- 目的：确认 MED_TRACE_RECORD 与 DRUG_PRESC_MASTER 当前索引，判定：
--   1) T_TRACE_CODE/TRACE_BILLNO 索引仍在（SQL01—04 的效率前提）；
--   2) 是否已存在 CREATE_TIME/MODIFY_TIME 索引（决定能否做同扫码时间窗反向审计）。
-- 若无 CREATE_TIME 索引，同窗口反向全量只能由DBA评估全扫代价后另行安排，
-- 不能只加 ROWNUM 后扫完整3个月。
SELECT IC.INDEX_NAME,IC.TABLE_NAME,IC.COLUMN_NAME,IC.COLUMN_POSITION,
       I.UNIQUENESS,I.STATUS
FROM ALL_IND_COLUMNS IC
JOIN ALL_INDEXES I
  ON I.OWNER=IC.INDEX_OWNER AND I.INDEX_NAME=IC.INDEX_NAME
WHERE (IC.TABLE_OWNER='DRUG_USER' AND IC.TABLE_NAME='MED_TRACE_RECORD')
   OR (IC.TABLE_OWNER='PHARMACY' AND IC.TABLE_NAME='DRUG_PRESC_MASTER')
ORDER BY IC.TABLE_NAME,IC.INDEX_NAME,IC.COLUMN_POSITION
