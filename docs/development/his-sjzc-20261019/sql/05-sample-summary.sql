-- HIS DRUG_USER.MED_TRACE_RECORD；先通过索引、账号及执行时段门禁，再执行本条。
-- 用户历史范围内取2026-10-11一天，最多100条扫码记录；仅输出汇总，不输出码或单号。
-- 不过滤 OUT/删除/拆零值：值域未经确认，避免把推测变成业务筛选。
SELECT IN_OUT_TYPE,KIND_TYPE,IS_DELETED,SPLIT_FLAG,
COUNT(*) AS SAMPLE_ROWS,COUNT(DISTINCT RECORD_ID) AS DISTINCT_RECORDS,
COUNT(PRESC_DETAILID) AS HAS_PRESC_DETAIL,COUNT(TRACE_BILLNO) AS HAS_TRACE_BILL,
COUNT(F_TRACE_CODE) AS HAS_F_CODE,COUNT(S_TRACE_CODE) AS HAS_S_CODE,
COUNT(T_TRACE_CODE) AS HAS_T_CODE,COUNT(MODIFY_TIME) AS HAS_MODIFY_TIME,
COUNT(DELETE_TIME) AS HAS_DELETE_TIME
FROM (
SELECT RECORD_ID,PRESC_DETAILID,TRACE_BILLNO,F_TRACE_CODE,S_TRACE_CODE,T_TRACE_CODE,
IN_OUT_TYPE,KIND_TYPE,IS_DELETED,SPLIT_FLAG,MODIFY_TIME,DELETE_TIME
FROM DRUG_USER.MED_TRACE_RECORD
WHERE CREATE_TIME>=TO_DATE('2026-10-11 00:00:00','yyyy-mm-dd hh24:mi:ss')
AND CREATE_TIME<TO_DATE('2026-10-12 00:00:00','yyyy-mm-dd hh24:mi:ss')
AND ROWNUM<=100
)
GROUP BY IN_OUT_TYPE,KIND_TYPE,IS_DELETED,SPLIT_FLAG
