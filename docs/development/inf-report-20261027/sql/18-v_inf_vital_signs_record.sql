-- 任务：INF-CRBSB-IMPL ｜ serial 已=病案号‖次数（CRBSB 视图原生，实测正确）故透传；
--   本层仅做：住院过滤(activity_type=6) + 窗口(2026-01-01) + 诊疗/患者锚点过滤 +
--   org 归一(370104000) + 科室 INFECT 映射 + OPERATION_TIME 字符串→DATE。
-- 列名与 CRBSB 视图一致（含其拼写截断列名，供 tables.py 按列名映射）。推送器零侵入。
-- =============================================================================
CREATE OR REPLACE FORCE VIEW "ODS"."V_INF_VITAL_SIGNS_RECORD" (
  "ID", "PATIENT_ID", "ACTIVITY_TYPE_CODE", "ACTIVITY_TYPE_NAME", "SERIAL_NUMBER", "PATIENT_NAME", "ID_CARD_TYPE_CODE", "ID_CARD_TYPE_NAME", "ID_CARD", "CREATE_DATE", "VENTILATORUSED_CODE", "VENTILATORUSED_NAME", "CRITICAL_CARE_CODE", "CRITICAL_CARE_NAME", "ORG_CODE", "ORG_NAME", "DEPT_CODE", "DEPT_NAME", "OPERATOR_ID", "OPERATION_TIME"
) AS
SELECT
  c.ID AS ID,
  c.PATIENT_ID AS PATIENT_ID,
  c.ACTIVITY_TYPE_CODE AS ACTIVITY_TYPE_CODE,
  '住院' AS ACTIVITY_TYPE_NAME,
  c.SERIAL_NUMBER AS SERIAL_NUMBER,
  c.PATIENT_NAME AS PATIENT_NAME,
  c.ID_CARD_TYPE_CODE AS ID_CARD_TYPE_CODE,
  c.ID_CARD_TYPE_NAME AS ID_CARD_TYPE_NAME,
  c.ID_CARD AS ID_CARD,
  TO_CHAR(TO_DATE(c.CREATE_DATE,'YYYYMMDDHH24MISS'),'YYYY-MM-DD HH24:MI:SS') AS CREATE_DATE,  -- 【v1.1 2026-11-15】原透传14位串，平台04"创建时间必填"且格式须标准——转标准日期串
  c.VENTILATORUSED_CODE AS VENTILATORUSED_CODE,
  c.VENTILATORUSED_NAME AS VENTILATORUSED_NAME,
  c.CRITICAL_CARE_CODE AS CRITICAL_CARE_CODE,
  c.CRITICAL_CARE_NAME AS CRITICAL_CARE_NAME,
  '370104000' AS ORG_CODE,
  '山东省第二人民医院' AS ORG_NAME,
  NVL((SELECT MAX(dd.INFECT_DEPT_CODE) FROM HIS.INFECT_DEPT_DICT dd WHERE TO_CHAR(dd.HIS_DEPT_CODE)=TO_CHAR(c.DEPT_CODE)), TO_CHAR(c.DEPT_CODE)) AS DEPT_CODE,
  NVL((SELECT MAX(x.INFECT_DEPT_NAME) FROM HIS.INFECT_DEPT_DICT x WHERE TO_CHAR(x.HIS_DEPT_CODE)=TO_CHAR(c.DEPT_CODE)),
      NVL((SELECT MAX(h.DEPT_NAME) FROM HIS.DEPT_DICT h WHERE TO_CHAR(h.DEPT_CODE)=TO_CHAR(c.DEPT_CODE)), c.DEPT_NAME)) AS DEPT_NAME,
  c.OPERATOR_ID AS OPERATOR_ID,
  TO_DATE(c.OPERATION_TIME,'YYYYMMDDHH24MISS') AS OPERATION_TIME
FROM CRBSB.EMR_VITAL_SIGNS_RECORD c
WHERE c.ACTIVITY_TYPE_CODE = '6'
  AND c.OPERATION_TIME >= '20260101000000'
  AND EXISTS (SELECT 1 FROM ODS.M_INF_FXHIS_ACTIVITY act
              WHERE TRIM(act.PATIENT_ID)=TRIM(c.PATIENT_ID) AND TRIM(act.SERIAL_NUMBER)=TRIM(c.SERIAL_NUMBER))
  AND EXISTS (SELECT 1 FROM HIS.PAT_MASTER_INDEX pat WHERE TRIM(pat.PATIENT_ID)=TRIM(c.PATIENT_ID))
WITH READ ONLY;

