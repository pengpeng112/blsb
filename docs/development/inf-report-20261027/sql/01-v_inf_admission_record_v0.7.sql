CREATE OR REPLACE FORCE VIEW "ODS"."V_INF_ADMISSION_RECORD" (
  "ID", "PATIENT_ID", "SERIAL_NUMBER", "PATIENT_NAME",
  "ID_CARD_TYPE_CODE", "ID_CARD_TYPE_NAME", "ID_CARD",
  "HEALTH_CARD_NO", "PAY_METHOD_CODE", "PAY_METHOD_NAME",
  "ADMISSION_NUM", "REG_NO",
  "ADMISSION_DATE", "ADMISSION_DEPT_CODE", "ADMISSION_DEPT_NAME", "WARD_NO",
  "DISCHARGE_DATE", "DISCHARGE_DEPT_CODE", "DISCHARGE_DEPT_NAME", "DISCHARGE_WARD",
  "ADMISSION_DAYS",
  "WM_OUTPATIENT_DIAGNOSIS_CODE", "WM_OUTPATIENT_DIAGNOSIS_NAME",
  "DISCHARGE_DIAGNOSIS_CODE", "DISCHARGE_DIAGNOSIS_NAME",
  "WM_OTHER_DIAGNOSIS_CODE", "WM_OTHER_DIAGNOSIS_NAME",
  "EXTERNAL_CAUSES_CODE", "EXTERNAL_CAUSES_NAME", "EXTERNAL_CAUSES_SYSTEM_NAME",
  "PATHOLOGICAL_DIAGNOSIS_CODE", "PATHOLOGICAL_DIAGNOSIS_NAME", "PATHOLOGICAL_NO",
  "ALLERGY_CODE", "ALLERGY_DRUG", "AUTOPSY_CODE",
  "CHIEF_PHYSICIAN_ID", "RESIDENT_PHYSICIAN_ID",
  "ACCEPT_ORG_CODE", "ACCEPT_ORG_NAME",
  "ORG_CODE", "ORG_NAME", "DEPT_CODE", "DEPT_NAME",
  "OPERATOR_ID", "OPERATION_TIME"
) AS
SELECT
  t.ID, t.PATIENT_ID, t.SERIAL_NUMBER, t.PATIENT_NAME,
  t.ID_CARD_TYPE_CODE, t.ID_CARD_TYPE_NAME, t.ID_CARD,
  t.HEALTH_CARD_NO, t.PAY_METHOD_CODE, t.PAY_METHOD_NAME,
  t.ADMISSION_NUM, t.REG_NO,
  t.ADMISSION_DATE, t.ADMISSION_DEPT_CODE, t.ADMISSION_DEPT_NAME, t.WARD_NO,
  t.DISCHARGE_DATE, t.DISCHARGE_DEPT_CODE, t.DISCHARGE_DEPT_NAME, t.DISCHARGE_WARD,
  t.ADMISSION_DAYS,
  t.WM_OUTPATIENT_DIAGNOSIS_CODE, t.WM_OUTPATIENT_DIAGNOSIS_NAME,
  t.DISCHARGE_DIAGNOSIS_CODE, t.DISCHARGE_DIAGNOSIS_NAME,
  t.WM_OTHER_DIAGNOSIS_CODE, t.WM_OTHER_DIAGNOSIS_NAME,
  t.EXTERNAL_CAUSES_CODE, t.EXTERNAL_CAUSES_NAME, t.EXTERNAL_CAUSES_SYSTEM_NAME,
  t.PATHOLOGICAL_DIAGNOSIS_CODE, t.PATHOLOGICAL_DIAGNOSIS_NAME, t.PATHOLOGICAL_NO,
  t.ALLERGY_CODE, t.ALLERGY_DRUG, t.AUTOPSY_CODE,
  t.CHIEF_PHYSICIAN_ID, t.RESIDENT_PHYSICIAN_ID,
  t.ACCEPT_ORG_CODE, t.ACCEPT_ORG_NAME,
  t.ORG_CODE, t.ORG_NAME, t.DEPT_CODE, t.DEPT_NAME,
  t.OPERATOR_ID, t.OPERATION_TIME
FROM (
  -- ===== v0.5 原逻辑原文（仅移除 WITH READ ONLY，列与过滤零改动）=====
  SELECT
    a.PATIENT_ID || '_' || a.VISIT_ID AS ID,

    a.PATIENT_ID AS PATIENT_ID,
    b.INP_NO || a.VISIT_ID AS SERIAL_NUMBER,
    SUBSTRB(TO_CHAR(b.NAME), 1, 100) AS PATIENT_NAME,

    '01' AS ID_CARD_TYPE_CODE,
    '居民身份证' AS ID_CARD_TYPE_NAME,
    NVL(TO_CHAR(b.ID_NO), '-') AS ID_CARD,

    CAST(NULL AS VARCHAR2(18)) AS HEALTH_CARD_NO,
    CASE REGEXP_REPLACE(TRIM(NVL(TO_CHAR(a.CHARGE_TYPE), '')), '[[:space:]]+', '')
      WHEN '职工医保' THEN '10'  WHEN '省直医保' THEN '10'
      WHEN '省内职工' THEN '11'  WHEN '省外职工' THEN '12'
      WHEN '居民医保' THEN '20'  WHEN '省内居民' THEN '21'
      WHEN '学生医保' THEN '21'  WHEN '儿童医保' THEN '21'
      WHEN '新农合' THEN '21'    WHEN '省外居民' THEN '22'
      WHEN '异地医保' THEN '22'
      WHEN '贫困救助' THEN '40'  WHEN '商业医疗保险' THEN '50'
      WHEN '全公费' THEN '60'
      WHEN '自费' THEN '70'      WHEN '全自费' THEN '70'
      WHEN '工伤' THEN '80'
      ELSE '99'
    END AS PAY_METHOD_CODE,
    CASE REGEXP_REPLACE(TRIM(NVL(TO_CHAR(a.CHARGE_TYPE), '')), '[[:space:]]+', '')
      WHEN '职工医保' THEN '职工基本医疗保险'
      WHEN '省直医保' THEN '职工基本医疗保险'
      WHEN '省内职工' THEN '本市职工基本医疗保险'
      WHEN '省外职工' THEN '外埠职工基本医疗保险'
      WHEN '居民医保' THEN '居民基本医疗保险'
      WHEN '省内居民' THEN '本市居民基本医疗保险'
      WHEN '学生医保' THEN '本市居民基本医疗保险'
      WHEN '儿童医保' THEN '本市居民基本医疗保险'
      WHEN '新农合' THEN '本市居民基本医疗保险'
      WHEN '省外居民' THEN '外埠居民基本医疗保险'
      WHEN '异地医保' THEN '外埠居民基本医疗保险'
      WHEN '贫困救助' THEN '贫困救助'
      WHEN '商业医疗保险' THEN '商业医疗保险'
      WHEN '全公费' THEN '全公费'
      WHEN '自费' THEN '全自费'
      WHEN '全自费' THEN '全自费'
      WHEN '工伤' THEN '其他社会保险'
      ELSE '其他'
    END AS PAY_METHOD_NAME,

    TO_CHAR(a.VISIT_ID) AS ADMISSION_NUM,
    SUBSTRB(NVL(TO_CHAR(a.INP_NO), TO_CHAR(b.INP_NO)), 1, 18) AS REG_NO,

    a.ADMISSION_DATE_TIME AS ADMISSION_DATE,
    NVL((SELECT MAX(dd.INFECT_DEPT_CODE) FROM HIS.INFECT_DEPT_DICT dd WHERE TO_CHAR(dd.HIS_DEPT_CODE) = TO_CHAR(a.DEPT_ADMISSION_TO)), TO_CHAR(a.DEPT_ADMISSION_TO)) AS ADMISSION_DEPT_CODE,
    NVL((SELECT MAX(x.INFECT_DEPT_NAME) FROM HIS.INFECT_DEPT_DICT x
        WHERE TO_CHAR(x.HIS_DEPT_CODE) = TO_CHAR(a.DEPT_ADMISSION_TO)),
        (SELECT MAX(dd.DEPT_NAME) FROM HIS.DEPT_DICT dd
        WHERE TO_CHAR(dd.DEPT_CODE) = TO_CHAR(a.DEPT_ADMISSION_TO))) AS ADMISSION_DEPT_NAME,
    CAST(NULL AS VARCHAR2(10)) AS WARD_NO,

    a.DISCHARGE_DATE_TIME AS DISCHARGE_DATE,
    NVL((SELECT MAX(dd.INFECT_DEPT_CODE) FROM HIS.INFECT_DEPT_DICT dd WHERE TO_CHAR(dd.HIS_DEPT_CODE) = TO_CHAR(a.DEPT_DISCHARGE_FROM)), TO_CHAR(a.DEPT_DISCHARGE_FROM)) AS DISCHARGE_DEPT_CODE,
    NVL((SELECT MAX(x.INFECT_DEPT_NAME) FROM HIS.INFECT_DEPT_DICT x
        WHERE TO_CHAR(x.HIS_DEPT_CODE) = TO_CHAR(a.DEPT_DISCHARGE_FROM)),
        (SELECT MAX(dd.DEPT_NAME) FROM HIS.DEPT_DICT dd
        WHERE TO_CHAR(dd.DEPT_CODE) = TO_CHAR(a.DEPT_DISCHARGE_FROM))) AS DISCHARGE_DEPT_NAME,
    CAST(NULL AS VARCHAR2(10)) AS DISCHARGE_WARD,

    CASE WHEN a.DISCHARGE_DATE_TIME IS NOT NULL AND a.ADMISSION_DATE_TIME IS NOT NULL
         THEN TO_CHAR(TRUNC(a.DISCHARGE_DATE_TIME) - TRUNC(a.ADMISSION_DATE_TIME) + 1)
         ELSE NULL END AS ADMISSION_DAYS,

    NVL(
      (SELECT SUBSTRB(LISTAGG(COALESCE(mc.GB, dg.DIAGNOSIS_CODE, mn.GB2), ',') WITHIN GROUP (ORDER BY dg.DIAGNOSIS_NO), 1, 400)
         FROM HIS.DIAGNOSIS dg,
              (SELECT 院标编码, MAX(TO_CHAR(国标编码)) GB FROM CDA.CDA_DICTIONARY WHERE 字典名称 = 'ICD-10诊断编码' AND 系统标识 = 'HIS' GROUP BY 院标编码) mc,
              (SELECT 院标名称, MAX(TO_CHAR(国标编码)) GB2 FROM CDA.CDA_DICTIONARY WHERE 字典名称 = 'ICD-10诊断编码' AND 系统标识 = 'HIS' GROUP BY 院标名称) mn
        WHERE mc.院标编码(+) = dg.DIAGNOSIS_CODE
          AND mn.院标名称(+) = dg.DIAGNOSIS_DESC
          AND dg.PATIENT_ID = a.PATIENT_ID AND dg.VISIT_ID = a.VISIT_ID
          AND dg.DIAGNOSIS_TYPE = '1'),
      (SELECT SUBSTRB(LISTAGG(NVL(mc.GB, dg.DIAGNOSIS_CODE), ',') WITHIN GROUP (ORDER BY dg.DIAGNOSIS_NO), 1, 400)
         FROM HIS.DIAGNOSIS dg,
              (SELECT 院标编码, MAX(TO_CHAR(国标编码)) GB FROM CDA.CDA_DICTIONARY WHERE 字典名称 = 'ICD-10诊断编码' AND 系统标识 = 'HIS' GROUP BY 院标编码) mc
        WHERE mc.院标编码(+) = dg.DIAGNOSIS_CODE
          AND dg.PATIENT_ID = a.PATIENT_ID AND dg.VISIT_ID = a.VISIT_ID
          AND dg.DIAGNOSIS_TYPE = '2')
    ) AS WM_OUTPATIENT_DIAGNOSIS_CODE,
    (SELECT SUBSTRB(LISTAGG(dg.DIAGNOSIS_DESC, ',') WITHIN GROUP (ORDER BY dg.DIAGNOSIS_NO), 1, 400)
       FROM HIS.DIAGNOSIS dg
      WHERE dg.PATIENT_ID = a.PATIENT_ID AND dg.VISIT_ID = a.VISIT_ID
        AND dg.DIAGNOSIS_TYPE = '1') AS WM_OUTPATIENT_DIAGNOSIS_NAME,

    (SELECT SUBSTRB(MAX(NVL((SELECT MAX(TO_CHAR(cd.国标编码))
                                FROM CDA.CDA_DICTIONARY cd
                               WHERE cd.字典名称 = 'ICD-10诊断编码' AND cd.系统标识 = 'HIS'
                                 AND cd.院标编码 = dg.DIAGNOSIS_CODE),
                             dg.DIAGNOSIS_CODE)), 1, 400)
       FROM HIS.DIAGNOSIS dg
      WHERE dg.PATIENT_ID = a.PATIENT_ID AND dg.VISIT_ID = a.VISIT_ID
        AND dg.DIAGNOSIS_TYPE = '3' AND dg.DIAGNOSIS_NO = 1) AS DISCHARGE_DIAGNOSIS_CODE,
    (SELECT SUBSTRB(MAX(dg.DIAGNOSIS_DESC), 1, 400)
       FROM HIS.DIAGNOSIS dg
      WHERE dg.PATIENT_ID = a.PATIENT_ID AND dg.VISIT_ID = a.VISIT_ID
        AND dg.DIAGNOSIS_TYPE = '3' AND dg.DIAGNOSIS_NO = 1) AS DISCHARGE_DIAGNOSIS_NAME,

    CAST(NULL AS VARCHAR2(400)) AS WM_OTHER_DIAGNOSIS_CODE,
    CAST(NULL AS VARCHAR2(400)) AS WM_OTHER_DIAGNOSIS_NAME,
    CAST(NULL AS VARCHAR2(50))  AS EXTERNAL_CAUSES_CODE,
    CAST(NULL AS VARCHAR2(250)) AS EXTERNAL_CAUSES_NAME,
    CAST(NULL AS VARCHAR2(2000)) AS EXTERNAL_CAUSES_SYSTEM_NAME,
    CAST(NULL AS VARCHAR2(50))  AS PATHOLOGICAL_DIAGNOSIS_CODE,
    CAST(NULL AS VARCHAR2(250)) AS PATHOLOGICAL_DIAGNOSIS_NAME,
    SUBSTRB(TO_CHAR(a.PATHOLOGY_NO), 1, 50) AS PATHOLOGICAL_NO,

    CASE WHEN a.ALERGY_DRUGS IS NOT NULL
          AND TRIM(TO_CHAR(a.ALERGY_DRUGS)) NOT IN ('', '无', '无过敏药物', '否认')
         THEN '1' ELSE '0' END AS ALLERGY_CODE,
    CASE WHEN a.ALERGY_DRUGS IS NOT NULL
          AND TRIM(TO_CHAR(a.ALERGY_DRUGS)) NOT IN ('', '无', '无过敏药物', '否认')
         THEN SUBSTRB(TO_CHAR(a.ALERGY_DRUGS), 1, 2000) END AS ALLERGY_DRUG,
    CAST(NULL AS VARCHAR2(1)) AS AUTOPSY_CODE,

    TO_CHAR(a.ATTENDING_DOCTOR) AS CHIEF_PHYSICIAN_ID,
    TO_CHAR(a.DOCTOR_IN_CHARGE) AS RESIDENT_PHYSICIAN_ID,

    CAST(NULL AS VARCHAR2(9))   AS ACCEPT_ORG_CODE,
    CAST(NULL AS VARCHAR2(100)) AS ACCEPT_ORG_NAME,

    '370104000' AS ORG_CODE,
    '山东省第二人民医院' AS ORG_NAME,
    NVL((SELECT MAX(dd.INFECT_DEPT_CODE) FROM HIS.INFECT_DEPT_DICT dd WHERE TO_CHAR(dd.HIS_DEPT_CODE) = TO_CHAR(a.DEPT_DISCHARGE_FROM)), TO_CHAR(a.DEPT_DISCHARGE_FROM)) AS DEPT_CODE,
    NVL((SELECT MAX(x.INFECT_DEPT_NAME) FROM HIS.INFECT_DEPT_DICT x
        WHERE TO_CHAR(x.HIS_DEPT_CODE) = TO_CHAR(a.DEPT_DISCHARGE_FROM)),
        (SELECT MAX(dd.DEPT_NAME) FROM HIS.DEPT_DICT dd
        WHERE TO_CHAR(dd.DEPT_CODE) = TO_CHAR(a.DEPT_DISCHARGE_FROM))) AS DEPT_NAME,

    NVL(TO_CHAR(a.ATTENDING_DOCTOR), TO_CHAR(a.DOCTOR_IN_CHARGE)) AS OPERATOR_ID,
    a.DISCHARGE_DATE_TIME AS OPERATION_TIME
  FROM HIS.PAT_VISIT a
  JOIN HIS.PAT_MASTER_INDEX b ON b.PATIENT_ID = a.PATIENT_ID
  WHERE a.DISCHARGE_DATE_TIME IS NOT NULL
    AND a.DISCHARGE_DATE_TIME >= TO_DATE('2026-01-01', 'YYYY-MM-DD')
) t
JOIN ODS.M_INF_FXHIS_ACTIVITY act
  ON TRIM(TO_CHAR(act.PATIENT_ID))     = TRIM(TO_CHAR(t.PATIENT_ID))
 AND TRIM(TO_CHAR(act.SERIAL_NUMBER))  = TRIM(TO_CHAR(t.SERIAL_NUMBER))
JOIN HIS.PAT_MASTER_INDEX pat
  ON TRIM(TO_CHAR(pat.PATIENT_ID)) = TRIM(TO_CHAR(t.PATIENT_ID))
WITH READ ONLY;

