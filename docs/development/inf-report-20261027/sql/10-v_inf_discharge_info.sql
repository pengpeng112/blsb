-- 传染病上报 · 出院记录（emr_discharge_info，接口 2.2.7 / emrDischargeInfo）V_INF_DISCHARGE_INFO
-- 版本：2026-11-15 v1（我方接管他方 FXHIS.V_EMR_DISCHARGE_INFO，用户拍板）
-- 参考：ODS.V_EMR_DISCHARGE_RECORD（三甲）驱动口径 = 嘉和文书分类码 MR_CLASS='EMR12.00'
--       + NVL(DELETE_FLAG,0)=0 + 每就诊首份（ROW_NUMBER）+ PAT_VISIT 出院信息；列集=FXHIS 版。
-- 与他方版差异（修复其缺陷）：
--   ① 诊疗过程/入院情况 = 嘉和出院记录正文真实内容（他方='诊疗过程'/'暂无此内容'占位）；
--   ② 入院诊断=DIAGNOSIS TYPE=2（国标映射，他方未滤 TYPE 全混入）；出院诊断 TYPE=3 同链；
--   ③ operation_time=文书 NVL(修订,创建)（他方=出院时间）——出院记录补写/修订可再推（幂等更新）。
-- 关联与及时性：id/serial 同他方历史口径（接管无重复）；诊疗锚点 EXISTS；op 水位 T+0；
--   推送 payload operationTime=上传时刻（既有机制）。
-- 窗口：文书创建>=2026-01-01。DBA 执行；回滚 DROP VIEW。
-- =============================================================================
CREATE OR REPLACE FORCE VIEW "ODS"."V_INF_DISCHARGE_INFO" (
  "ID","PATIENT_ID","SERIAL_NUMBER","PATIENT_NAME",
  "ID_CARD_TYPE_CODE","ID_CARD_TYPE_NAME","ID_CARD",
  "ADMISSION_DATE","DISCHARGE_DATE",
  "ADMISSION_DIAGNOSIS_CODE","ADMISSION_DIAGNOSIS_NAME",
  "DISCHARGE_DIAGNOSIS_CODE","DISCHARGE_DIAGNOSIS_NAME",
  "ADMISSION_DESC","TREATMENT_DESC",
  "DISEASE_PROGRESSION_CODE","DISEASE_PROGRESSION_NAME",
  "DEPT_CODE","DEPT_NAME","ORG_CODE","ORG_NAME","OPERATOR_ID","OPERATION_TIME"
) AS
WITH w AS (
  SELECT d.PATIENT_ID, d.VISIT_ID, d.FILE_UNIQUE_ID,
         d.CREATOR_ID, d.CREATE_DATE_TIME, d.LAST_MODIFY_DATE_TIME,
         ROW_NUMBER() OVER (PARTITION BY d.PATIENT_ID, d.VISIT_ID
                            ORDER BY d.CREATE_DATE_TIME, ROWID) rn
    FROM JHEMR.JHMR_FILE_INDEX d
   WHERE d.MR_CLASS = 'EMR12.00'
     AND NVL(d.DELETE_FLAG,0) = 0
     AND d.CREATE_DATE_TIME >= DATE'2026-01-01'
)
SELECT
  w.PATIENT_ID||'_'||w.VISIT_ID AS ID,
  w.PATIENT_ID AS PATIENT_ID,
  pmi.INP_NO||w.VISIT_ID AS SERIAL_NUMBER,
  pmi.NAME AS PATIENT_NAME,
  '01' AS ID_CARD_TYPE_CODE,
  '居民身份证' AS ID_CARD_TYPE_NAME,
  NVL(pmi.ID_NO,'-') AS ID_CARD,
  pv.ADMISSION_DATE_TIME AS ADMISSION_DATE,
  pv.DISCHARGE_DATE_TIME AS DISCHARGE_DATE,
  (SELECT SUBSTRB(LISTAGG(NVL((SELECT MAX(TO_CHAR(cd.国标编码)) FROM CDA.CDA_DICTIONARY cd WHERE cd.字典名称='ICD-10诊断编码' AND cd.系统标识='HIS' AND cd.院标编码=dg.DIAGNOSIS_CODE), dg.DIAGNOSIS_CODE),'||') WITHIN GROUP (ORDER BY dg.DIAGNOSIS_NO),1,400)
     FROM HIS.DIAGNOSIS dg WHERE dg.PATIENT_ID=w.PATIENT_ID AND dg.VISIT_ID=w.VISIT_ID AND dg.DIAGNOSIS_TYPE='2' AND dg.DIAGNOSIS_CODE IS NOT NULL) AS ADMISSION_DIAGNOSIS_CODE,
  (SELECT SUBSTRB(LISTAGG(dg.DIAGNOSIS_DESC,'||') WITHIN GROUP (ORDER BY dg.DIAGNOSIS_NO),1,400)
     FROM HIS.DIAGNOSIS dg WHERE dg.PATIENT_ID=w.PATIENT_ID AND dg.VISIT_ID=w.VISIT_ID AND dg.DIAGNOSIS_TYPE='2' AND dg.DIAGNOSIS_CODE IS NOT NULL) AS ADMISSION_DIAGNOSIS_NAME,
  (SELECT SUBSTRB(LISTAGG(NVL((SELECT MAX(TO_CHAR(cd.国标编码)) FROM CDA.CDA_DICTIONARY cd WHERE cd.字典名称='ICD-10诊断编码' AND cd.系统标识='HIS' AND cd.院标编码=dg.DIAGNOSIS_CODE), dg.DIAGNOSIS_CODE),'||') WITHIN GROUP (ORDER BY dg.DIAGNOSIS_NO),1,400)
     FROM HIS.DIAGNOSIS dg WHERE dg.PATIENT_ID=w.PATIENT_ID AND dg.VISIT_ID=w.VISIT_ID AND dg.DIAGNOSIS_TYPE='3' AND dg.DIAGNOSIS_CODE IS NOT NULL) AS DISCHARGE_DIAGNOSIS_CODE,
  (SELECT SUBSTRB(LISTAGG(dg.DIAGNOSIS_DESC,'||') WITHIN GROUP (ORDER BY dg.DIAGNOSIS_NO),1,400)
     FROM HIS.DIAGNOSIS dg WHERE dg.PATIENT_ID=w.PATIENT_ID AND dg.VISIT_ID=w.VISIT_ID AND dg.DIAGNOSIS_TYPE='3' AND dg.DIAGNOSIS_CODE IS NOT NULL) AS DISCHARGE_DIAGNOSIS_NAME,
  DBMS_LOB.SUBSTR(c.MR_CONTENT, 2000, 1) AS ADMISSION_DESC,    -- 出院记录正文（含入院情况/诊疗过程整段；节点解析二期）
  DBMS_LOB.SUBSTR(c.MR_CONTENT, 2000, 1) AS TREATMENT_DESC,
  CASE pv.DISCHARGE_DISPOSITION WHEN '1' THEN '1' WHEN '4' THEN '2' WHEN '3' THEN '5' ELSE '9' END AS DISEASE_PROGRESSION_CODE,
  CASE pv.DISCHARGE_DISPOSITION WHEN '1' THEN '治愈' WHEN '4' THEN '好转' WHEN '3' THEN '死亡' ELSE '其他' END AS DISEASE_PROGRESSION_NAME,
  NVL((SELECT MAX(dd.INFECT_DEPT_CODE) FROM HIS.INFECT_DEPT_DICT dd WHERE dd.HIS_DEPT_CODE=pv.DEPT_DISCHARGE_FROM), TO_CHAR(pv.DEPT_DISCHARGE_FROM)) AS DEPT_CODE,
  NVL((SELECT MAX(x.INFECT_DEPT_NAME) FROM HIS.INFECT_DEPT_DICT x WHERE x.HIS_DEPT_CODE=pv.DEPT_DISCHARGE_FROM),
      (SELECT MAX(b.DEPT_NAME) FROM HIS.DEPT_DICT b WHERE b.DEPT_CODE=pv.DEPT_DISCHARGE_FROM)) AS DEPT_NAME,
  '370104000' AS ORG_CODE,
  '山东省第二人民医院' AS ORG_NAME,
  TO_CHAR(w.CREATOR_ID) AS OPERATOR_ID,
  NVL(w.LAST_MODIFY_DATE_TIME, w.CREATE_DATE_TIME) AS OPERATION_TIME
FROM w
JOIN JHEMR.JHMR_FILE_CONTENT_TEXT c ON c.FILE_UNIQUE_ID = w.FILE_UNIQUE_ID
JOIN HIS.PAT_MASTER_INDEX pmi ON pmi.PATIENT_ID = w.PATIENT_ID
LEFT JOIN HIS.PAT_VISIT pv ON pv.PATIENT_ID=w.PATIENT_ID AND pv.VISIT_ID=w.VISIT_ID
WHERE w.rn = 1
  AND EXISTS (SELECT 1 FROM ODS.M_INF_FXHIS_ACTIVITY act
              WHERE TRIM(act.PATIENT_ID)=TRIM(w.PATIENT_ID)
                AND TRIM(act.SERIAL_NUMBER)=TRIM(pmi.INP_NO||w.VISIT_ID))
WITH READ ONLY;

