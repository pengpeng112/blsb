-- 传染病上报扩展 · V_INF_ORDER_ITEM 医嘱处方条目（回源表重建版，2026-11-13）
-- 源：HIS.ORDERS + ODS.PUB_LYYP（药品映射）+ DRUG_DICT。
-- 主子关联：ORDER_ID=主表 V_INF_ORDER.ID=patient_id‖visit_id‖order_no‖order_sub_no（同源同键）。
-- 剂量单位/中药字段映射沿用 CRBSB.emr_order_item 的 CASE。
-- 过滤：ORDER_CLASS in('A','B') + 有诊断 + 窗口 + 诊疗锚点。OPERATION_TIME=START_DATE_TIME(DATE)。
-- 【2026-11-14 修正】PUB_LYYP 一码多行 + 大表 LEFT JOIN 致 order_item 行集放大且全窗口超时；
--   最终方案：**去掉 JOIN PUB_LYYP**，drug_code/drug_name 改**标量子查询**（标准编码优先、
--   ORDER_CODE/ORDER_TEXT 兜底），与 order 主表同执行路径（his.orders+pat_visit+pmi+锚点），
--   消除 JOIN 放大与超时，药品映射语义与 CRBSB 一致。
-- =============================================================================
CREATE OR REPLACE FORCE VIEW "ODS"."V_INF_ORDER_ITEM" (
  "ID","ORDER_ID","DRUG_CODE","DRUG_NAME","DRUG_SPECIFICATIONS","DRUG_DOSAGE_CODE",
  "DRUG_DOSAGE_UNIT_CODE","DRUG_DOSAGE_UNIT_NAME","DRUG_DOSAGE_TOTAL","TCM_PRESCRIPTION",
  "TCM_NUMBER","TCM_DECOCTION_METHOD","TCM_USE_METHOD","OPERATOR_ID","OPERATION_TIME"
) AS
SELECT
  a.PATIENT_ID||'_'||a.VISIT_ID||'_'||a.ORDER_NO||'_'||a.ORDER_SUB_NO AS ID,
  a.PATIENT_ID||'_'||a.VISIT_ID||'_'||a.ORDER_NO||'_'||a.ORDER_SUB_NO AS ORDER_ID,
  NVL(NVL((SELECT MAX(c.药品编码) FROM ODS.PUB_LYYP c WHERE c.HIS药品编码=a.ORDER_CODE), a.ORDER_CODE),'-') AS DRUG_CODE,
  NVL((SELECT MAX(c.药品名称) FROM ODS.PUB_LYYP c WHERE c.HIS药品编码=a.ORDER_CODE), a.ORDER_TEXT) AS DRUG_NAME,
  NVL((SELECT MAX(m.DRUG_SPEC) FROM HIS.DRUG_DICT m WHERE a.ORDER_CODE=m.DRUG_CODE),'-') AS DRUG_SPECIFICATIONS,
  NVL(TRIM(TRAILING '.' FROM TO_CHAR(a.DOSAGE,'fm9990.99')),'-') AS DRUG_DOSAGE_CODE,
  CASE WHEN a.DOSAGE_UNITS IN ('g','克') THEN '01' WHEN a.DOSAGE_UNITS IN ('mg','毫克') THEN '02'
       WHEN a.DOSAGE_UNITS IN ('ug') THEN '03' WHEN a.DOSAGE_UNITS IN ('升') THEN '05'
       WHEN a.DOSAGE_UNITS IN ('ml') THEN '06'
       WHEN a.DOSAGE_UNITS IN ('IU','iu','万IU','万iu') THEN '07'
       WHEN a.DOSAGE_UNITS IN ('u','万u') THEN '08' ELSE '99' END AS DRUG_DOSAGE_UNIT_CODE,
  CASE WHEN a.DOSAGE_UNITS IN ('g','克') THEN '克（g）' WHEN a.DOSAGE_UNITS IN ('mg','毫克') THEN '毫克（mg）'
       WHEN a.DOSAGE_UNITS IN ('ug') THEN '微克（μg）' WHEN a.DOSAGE_UNITS IN ('升') THEN '升（L）'
       WHEN a.DOSAGE_UNITS IN ('ml') THEN '毫升（ml）'
       WHEN a.DOSAGE_UNITS IN ('IU','iu','万IU','万iu') THEN '国际单位（IU）'
       WHEN a.DOSAGE_UNITS IN ('u','万u') THEN '单位（U）' ELSE '其他' END AS DRUG_DOSAGE_UNIT_NAME,
  '' AS DRUG_DOSAGE_TOTAL,
  CASE WHEN a.ORDER_CLASS='B' THEN a.ORDER_TEXT ELSE '' END AS TCM_PRESCRIPTION,
  '' AS TCM_NUMBER,
  '-' AS TCM_DECOCTION_METHOD,
  CASE WHEN a.ORDER_CLASS='B' THEN a.FREQ_DETAIL ELSE '' END AS TCM_USE_METHOD,
  a.DOCTOR AS OPERATOR_ID,
  a.START_DATE_TIME AS OPERATION_TIME
FROM HIS.ORDERS a
JOIN HIS.PAT_VISIT b ON a.PATIENT_ID=b.PATIENT_ID AND a.VISIT_ID=b.VISIT_ID
LEFT JOIN HIS.PAT_MASTER_INDEX pmi ON pmi.PATIENT_ID=a.PATIENT_ID
WHERE a.ORDER_CLASS IN ('A','B')
  AND a.START_DATE_TIME >= DATE'2026-01-01'
  AND EXISTS (SELECT 1 FROM HIS.DIAGNOSIS zd WHERE a.PATIENT_ID=zd.PATIENT_ID AND a.VISIT_ID=zd.VISIT_ID)
  AND EXISTS (SELECT 1 FROM ODS.M_INF_FXHIS_ACTIVITY act
              WHERE TRIM(act.PATIENT_ID)=TRIM(a.PATIENT_ID)
                AND TRIM(act.SERIAL_NUMBER)=TRIM(pmi.INP_NO||a.VISIT_ID))
WITH READ ONLY;

