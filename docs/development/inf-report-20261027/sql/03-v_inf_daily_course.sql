-- 任务：INF-DESIGN-20261027 ｜ 库：ODS ｜ 目标接口 /hclient/emr/receive/emrDailyCourse
-- 源：同 V_INF_FIRST_COURSE（JHEMR.JHMR_FILE_INDEX + JHMR_FILE_CONTENT_TEXT）
-- 正文 course / order_content 均为"建议填"，纯文本整段方案满足规范（FIELD_MAPPING §3）
-- 注意：TOPIC 过滤为保守写法，真实分布（日常病程记录/病程记录/病程录…）抽样后收紧
-- =============================================================================

CREATE OR REPLACE FORCE VIEW "ODS"."V_INF_DAILY_COURSE" (
  "ID", "PATIENT_ID", "SERIAL_NUMBER", "PATIENT_NAME",
  "ID_CARD_TYPE_CODE", "ID_CARD_TYPE_NAME", "ID_CARD",
  "WARD_NAME", "WARD_NO", "BED_NO", "CREATE_TIME",
  "COURSE", "ORDER_CONTENT", "OBSERVATION_RESULT", "TREATMENT",
  "DISEASE_PROGRESSION_CODE", "DISEASE_PROGRESSION_NAME",
  "ORG_CODE", "ORG_NAME", "DEPT_CODE", "DEPT_NAME",
  "OPERATOR_ID", "OPERATION_TIME"
) AS
SELECT
  t.PATIENT_ID || '_' || t.VISIT_ID || '_' || t.FILE_UNIQUE_ID AS ID,

  t.PATIENT_ID AS PATIENT_ID,
  pmi.INP_NO || t.VISIT_ID AS SERIAL_NUMBER,  -- crbsb 口径=病案号||住院次数
  SUBSTRB(TO_CHAR(pmi.NAME), 1, 100) AS PATIENT_NAME,

  '01' AS ID_CARD_TYPE_CODE,
  '居民身份证' AS ID_CARD_TYPE_NAME,
  NVL(TO_CHAR(pmi.ID_NO), '-') AS ID_CARD,  -- crbsb 同款兜底

  t.DEPT_CODE AS WARD_NAME,
  CAST(NULL AS VARCHAR2(10)) AS WARD_NO,
  SUBSTRB(TO_CHAR(t.FILE_NO), 1, 10) AS BED_NO,
  t.CREATE_DATE_TIME AS CREATE_TIME,

  DBMS_LOB.SUBSTR(c.MR_CONTENT, 2000, 1) AS COURSE,              -- 住院病程正文（建议填）；截2000字=GBK库SQL层VARCHAR2 4000字节上限（实测3900字触发ORA-06502，与三甲2000同因）；全文推送二期走CLOB直读
  CAST(NULL AS VARCHAR2(2000)) AS ORDER_CONTENT,                 -- 医嘱内容二期关联医嘱表
  CAST(NULL AS VARCHAR2(2000)) AS OBSERVATION_RESULT,            -- 中医四诊，非必填
  CAST(NULL AS VARCHAR2(2000)) AS TREATMENT,                     -- 辨证论治，非必填
  CAST(NULL AS VARCHAR2(1))  AS DISEASE_PROGRESSION_CODE,
  CAST(NULL AS VARCHAR2(50)) AS DISEASE_PROGRESSION_NAME,

  '370104000' AS ORG_CODE,
  '山东省第二人民医院' AS ORG_NAME,
  NVL((SELECT MAX(dd.INFECT_DEPT_CODE) FROM HIS.INFECT_DEPT_DICT dd WHERE TO_CHAR(dd.HIS_DEPT_CODE) = TO_CHAR(t.DEPT_CODE)), TO_CHAR(t.DEPT_CODE)) AS DEPT_CODE,  -- crbsb 口径 INFECT 映射+原码兜底
  NVL((SELECT MAX(x.INFECT_DEPT_NAME) FROM HIS.INFECT_DEPT_DICT x
      WHERE TO_CHAR(x.HIS_DEPT_CODE) = TO_CHAR(t.DEPT_CODE)),
      (SELECT MAX(dd.DEPT_NAME) FROM HIS.DEPT_DICT dd
      WHERE TO_CHAR(dd.DEPT_CODE) = TO_CHAR(t.DEPT_CODE))) AS DEPT_NAME,

  NVL(TO_CHAR(t.LAST_MODIFY_USER_ID), TO_CHAR(t.CREATOR_ID)) AS OPERATOR_ID,
  NVL(t.LAST_MODIFY_DATE_TIME, t.CREATE_DATE_TIME) AS OPERATION_TIME
FROM JHEMR.JHMR_FILE_INDEX t
JOIN JHEMR.JHMR_FILE_CONTENT_TEXT c ON c.FILE_UNIQUE_ID = t.FILE_UNIQUE_ID
JOIN HIS.PAT_VISIT pv ON pv.PATIENT_ID = t.PATIENT_ID AND pv.VISIT_ID = t.VISIT_ID
JOIN HIS.PAT_MASTER_INDEX pmi ON pmi.PATIENT_ID = t.PATIENT_ID
WHERE t.TOPIC LIKE '%病程记录%'
  AND t.TOPIC NOT LIKE '%首次%'
  AND t.TOPIC NOT LIKE '%术后%'                                   -- 排除首次/术后首次（初版排除法，抽样后改白名单）
  AND NVL(t.DELETE_FLAG, 0) = 0
  AND NVL(t.LAST_MODIFY_DATE_TIME, t.CREATE_DATE_TIME) >= TO_DATE('2026-01-01', 'YYYY-MM-DD')
WITH READ ONLY;
