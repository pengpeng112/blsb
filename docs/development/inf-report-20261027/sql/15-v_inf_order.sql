-- 传染病上报扩展 · V_INF_ORDER 医嘱处方（回源表重建版，2026-11-13）
-- 源：HIS.ORDERS（医嘱主表，ODS OGG 镜像）+ PAT_VISIT + PAT_MASTER_INDEX + DRUG_DICT。
-- 回源表原因：CRBSB.emr_order 包一层加锚点 EXISTS 后大表超时；回源表可控窗口+锚点。
-- 口径：serial=INP_NO‖VISIT_ID（诊疗锚点键）；org=370104000；科室 INFECT 映射；
--   activity_type=6 住院；ORDER_CLASS in('A','B')=长期/临时医嘱（CRBSB 口径）；
--   时间字段 'YYYY-MM-DD HH24:MI:SS'；OPERATION_TIME=START_DATE_TIME(DATE) 作水位。
-- id=patient_id‖visit_id‖order_no‖order_sub_no（CRBSB 原生复合 id，与子表 order_id 同源）。
-- =============================================================================
CREATE OR REPLACE FORCE VIEW "ODS"."V_INF_ORDER" (
  "ID","PATIENT_ID","ACTIVITY_TYPE_CODE","ACTIVITY_TYPE_NAME","SERIAL_NUMBER","PATIENT_NAME",
  "ID_CARD_TYPE_CODE","ID_CARD_TYPE_NAME","ID_CARD","PRESCRIPTION_NO","PRESCRIPTION_TYPE_CODE",
  "PRESCRIPTION_ISSUANCE_DATE","PRESCRIPTION_VALIDITY_DAYS","EXCUTE_DATE","PRESCRIPTION_ISSUANCE_ID",
  "PRESCRIPTION_DISPENSING_ID","PRESCRIPTION_NOTES","ORG_CODE","ORG_NAME","DEPT_CODE","DEPT_NAME",
  "OPERATOR_ID","OPERATION_TIME"
) AS
SELECT
  a.PATIENT_ID||'_'||a.VISIT_ID||'_'||a.ORDER_NO||'_'||a.ORDER_SUB_NO AS ID,
  a.PATIENT_ID AS PATIENT_ID,
  '6' AS ACTIVITY_TYPE_CODE,
  '住院' AS ACTIVITY_TYPE_NAME,
  pmi.INP_NO || a.VISIT_ID AS SERIAL_NUMBER,
  pmi.NAME AS PATIENT_NAME,
  '01' AS ID_CARD_TYPE_CODE,
  '居民身份证' AS ID_CARD_TYPE_NAME,
  NVL(pmi.ID_NO,'-') AS ID_CARD,
  a.ORDER_NO||'_'||a.ORDER_SUB_NO AS PRESCRIPTION_NO,
  (SELECT MAX(m.DRUG_INDICATOR) FROM HIS.DRUG_DICT m WHERE a.ORDER_CODE=m.DRUG_CODE) AS PRESCRIPTION_TYPE_CODE,
  TO_CHAR(a.START_DATE_TIME,'YYYY-MM-DD HH24:MI:SS') AS PRESCRIPTION_ISSUANCE_DATE,
  SUBSTRB(TO_CHAR(NVL(TRUNC(a.STOP_DATE_TIME-a.START_DATE_TIME),0)),1,2) AS PRESCRIPTION_VALIDITY_DAYS,  -- 【v1.1】平台04"处方有效天数不超过2位"——超长疗程截2位（CRBSB原版无截断）
  TO_CHAR(a.START_DATE_TIME,'YYYY-MM-DD HH24:MI:SS') AS EXCUTE_DATE,
  a.DOCTOR_USER AS PRESCRIPTION_ISSUANCE_ID,
  '' AS PRESCRIPTION_DISPENSING_ID,
  '' AS PRESCRIPTION_NOTES,
  '370104000' AS ORG_CODE,
  '山东省第二人民医院' AS ORG_NAME,
  (SELECT MAX(dd.INFECT_DEPT_CODE) FROM HIS.INFECT_DEPT_DICT dd WHERE dd.HIS_DEPT_CODE=a.ORDERING_DEPT) AS DEPT_CODE,
  (SELECT MAX(dd.INFECT_DEPT_NAME) FROM HIS.INFECT_DEPT_DICT dd WHERE dd.HIS_DEPT_CODE=a.ORDERING_DEPT) AS DEPT_NAME,
  a.DOCTOR AS OPERATOR_ID,
  a.START_DATE_TIME AS OPERATION_TIME
FROM HIS.ORDERS a
JOIN HIS.PAT_VISIT b ON a.PATIENT_ID=b.PATIENT_ID AND a.VISIT_ID=b.VISIT_ID
LEFT JOIN HIS.PAT_MASTER_INDEX pmi ON pmi.PATIENT_ID=a.PATIENT_ID
WHERE a.ORDER_CLASS IN ('A','B')
  AND a.START_DATE_TIME >= DATE'2026-01-01'
  AND EXISTS (SELECT 1 FROM HIS.DIAGNOSIS zd WHERE a.PATIENT_ID=zd.PATIENT_ID AND a.VISIT_ID=zd.VISIT_ID)
  AND EXISTS (SELECT 1 FROM ODS.M_INF_FXHIS_ACTIVITY act
              WHERE TRIM(act.PATIENT_ID)=TRIM(a.PATIENT_ID)
                AND TRIM(act.SERIAL_NUMBER)=TRIM(pmi.INP_NO||a.VISIT_ID))
WITH READ ONLY;

