CREATE OR REPLACE FORCE VIEW "ODS"."V_INF_EX_CLINICAL" (
  "ID", "PATIENT_ID", "ACTIVITY_TYPE_CODE", "ACTIVITY_TYPE_NAME",
  "SERIAL_NUMBER", "PATIENT_NAME",
  "ID_CARD_TYPE_CODE", "ID_CARD_TYPE_NAME", "ID_CARD",
  "WARD_NAME", "WARD_NO", "BED_NO",
  "APPLICATION_FORM_NO", "APPLY_ORG_CODE", "APPLY_ORG_NAME",
  "APPLY_DEPT_CODE", "APPLY_DEPT_NAME",
  "SYMPTOM_START_DATE", "SYMPTOM_END_DATE", "SYMPTOM_DESC", "TREATMENT_DESC",
  "SPECIAL_EXAMINATION_CODE",
  "EXAMINATION_TYPE_CODE", "EXAMINATION_TYPE_NAME",
  "EXAMINATION_OBJECTIVE_DESC", "EXAMINATION_SUBJECTIVE_DESC", "EXAMINATION_NOTES",
  "EXAMINATION_REPORT_NO", "EXAMINATION_REPORT_DATE", "EXAMINATION_REPORT_ID",
  "ORG_CODE", "ORG_NAME", "DEPT_CODE", "DEPT_NAME",
  "OPERATOR_ID", "OPERATION_TIME"
) AS
SELECT
  t.ID,
  t.PATIENT_ID,
  t.ACTIVITY_TYPE_CODE,
  t.ACTIVITY_TYPE_NAME,
  t.SERIAL_NUMBER,
  t.PATIENT_NAME,
  t.ID_CARD_TYPE_CODE,
  t.ID_CARD_TYPE_NAME,
  t.ID_CARD,
  t.WARD_NAME,
  t.WARD_NO,
  t.BED_NO,
  t.APPLICATION_FORM_NO,
  t.APPLY_ORG_CODE,
  t.APPLY_ORG_NAME,
  t.APPLY_DEPT_CODE,
  t.APPLY_DEPT_NAME,
  t.SYMPTOM_START_DATE,
  t.SYMPTOM_END_DATE,
  t.SYMPTOM_DESC,
  t.TREATMENT_DESC,
  t.SPECIAL_EXAMINATION_CODE,
  t.EXAMINATION_TYPE_CODE,
  t.EXAMINATION_TYPE_NAME,
  t.EXAMINATION_OBJECTIVE_DESC,
  t.EXAMINATION_SUBJECTIVE_DESC,
  t.EXAMINATION_NOTES,
  t.EXAMINATION_REPORT_NO,
  t.EXAMINATION_REPORT_DATE,
  t.EXAMINATION_REPORT_ID,
  t.ORG_CODE,
  t.ORG_NAME,
  t.DEPT_CODE,
  t.DEPT_NAME,
  t.OPERATOR_ID,
  t.OPERATION_TIME
FROM (
SELECT
  m.EXAM_NO AS ID,
  m.PATIENT_ID AS PATIENT_ID,
  '6' AS ACTIVITY_TYPE_CODE,
  '住院' AS ACTIVITY_TYPE_NAME,
  pmi.INP_NO || m.VISIT_ID AS SERIAL_NUMBER,
  SUBSTRB(TO_CHAR(m.NAME), 1, 100) AS PATIENT_NAME,
  '01' AS ID_CARD_TYPE_CODE,
  '居民身份证' AS ID_CARD_TYPE_NAME,
  NVL(TO_CHAR(pmi.ID_NO), '-') AS ID_CARD,
  CAST(NULL AS VARCHAR2(50)) AS WARD_NAME,
  CAST(NULL AS VARCHAR2(10)) AS WARD_NO,
  CAST(NULL AS VARCHAR2(10)) AS BED_NO,
  SUBSTRB(TO_CHAR(m.EXAM_NO), 1, 50) AS APPLICATION_FORM_NO,
  '370104000' AS APPLY_ORG_CODE,
  '山东省第二人民医院' AS APPLY_ORG_NAME,
  NVL((SELECT MAX(dd.INFECT_DEPT_CODE) FROM HIS.INFECT_DEPT_DICT dd WHERE TO_CHAR(dd.HIS_DEPT_CODE)=TO_CHAR(m.REQ_DEPT)), TO_CHAR(m.REQ_DEPT)) AS APPLY_DEPT_CODE,
  NVL((SELECT MAX(x.INFECT_DEPT_NAME) FROM HIS.INFECT_DEPT_DICT x WHERE TO_CHAR(x.HIS_DEPT_CODE)=TO_CHAR(m.REQ_DEPT)),
      (SELECT MAX(q.DEPT_NAME) FROM HIS.DEPT_DICT q WHERE TO_CHAR(q.DEPT_CODE)=TO_CHAR(m.REQ_DEPT))) AS APPLY_DEPT_NAME,
  CAST(NULL AS VARCHAR2(20)) AS SYMPTOM_START_DATE,
  CAST(NULL AS VARCHAR2(20)) AS SYMPTOM_END_DATE,
  SUBSTRB(TO_CHAR(m.CLIN_SYMP),1,2000) AS SYMPTOM_DESC,
  SUBSTRB(TO_CHAR(m.PHYS_SIGN),1,2000) AS TREATMENT_DESC,
  CAST(NULL AS VARCHAR2(20)) AS SPECIAL_EXAMINATION_CODE,
  NVL((SELECT MAX(TO_CHAR(q.EXAM_CLASS_CODE)) FROM HIS.EXAM_CLASS_DICT q WHERE q.EXAM_CLASS_NAME = m.EXAM_CLASS), '99') AS EXAMINATION_TYPE_CODE,
  TO_CHAR(m.EXAM_CLASS) AS EXAMINATION_TYPE_NAME,
  SUBSTRB(TO_CHAR(r.DESCRIPTION),1,2000) AS EXAMINATION_OBJECTIVE_DESC,
  SUBSTRB(TO_CHAR(r.IMPRESSION),1,2000) AS EXAMINATION_SUBJECTIVE_DESC,
  SUBSTRB(TO_CHAR(r.RECOMMENDATION),1,2000) AS EXAMINATION_NOTES,
  TO_CHAR(m.EXAM_NO) AS EXAMINATION_REPORT_NO,
  r.REPORT_TIME AS EXAMINATION_REPORT_DATE,
  TO_CHAR(r.REPORTER) AS EXAMINATION_REPORT_ID,
  '370104000' AS ORG_CODE,
  '山东省第二人民医院' AS ORG_NAME,
  NVL((SELECT MAX(dd.INFECT_DEPT_CODE) FROM HIS.INFECT_DEPT_DICT dd WHERE TO_CHAR(dd.HIS_DEPT_CODE)=TO_CHAR(m.EXAM_SUBDEPT)),
      NVL((SELECT MAX(dd2.INFECT_DEPT_CODE) FROM HIS.INFECT_DEPT_DICT dd2 WHERE TO_CHAR(dd2.HIS_DEPT_CODE)=TO_CHAR(m.REQ_DEPT)),
          NVL(TO_CHAR(m.EXAM_SUBDEPT), TO_CHAR(m.REQ_DEPT)))) AS DEPT_CODE,
  CASE WHEN m.EXAM_SUBDEPT IS NOT NULL THEN
       NVL((SELECT MAX(dd.INFECT_DEPT_NAME) FROM HIS.INFECT_DEPT_DICT dd WHERE TO_CHAR(dd.HIS_DEPT_CODE)=TO_CHAR(m.EXAM_SUBDEPT)),
           (SELECT MAX(h.DEPT_NAME) FROM HIS.DEPT_DICT h WHERE TO_CHAR(h.DEPT_CODE)=TO_CHAR(m.EXAM_SUBDEPT)))
     ELSE
       NVL((SELECT MAX(dd.INFECT_DEPT_NAME) FROM HIS.INFECT_DEPT_DICT dd WHERE TO_CHAR(dd.HIS_DEPT_CODE)=TO_CHAR(m.REQ_DEPT)),
           (SELECT MAX(h.DEPT_NAME) FROM HIS.DEPT_DICT h WHERE TO_CHAR(h.DEPT_CODE)=TO_CHAR(m.REQ_DEPT)))
     END AS DEPT_NAME,
  NVL(TO_CHAR(r.REPORTER), TO_CHAR(m.CONFIRM_DOCT)) AS OPERATOR_ID,
  NVL(r.REPORT_TIME, m.REPORT_DATE_TIME) AS OPERATION_TIME
FROM HIS.EXAM_MASTER m
JOIN HIS.EXAM_REPORT r ON r.EXAM_NO = m.EXAM_NO
JOIN HIS.PAT_VISIT pv ON pv.PATIENT_ID=m.PATIENT_ID AND pv.VISIT_ID=m.VISIT_ID
JOIN HIS.PAT_MASTER_INDEX pmi ON pmi.PATIENT_ID=m.PATIENT_ID
WHERE NVL(m.REPORT_DATE_TIME, m.REQ_DATE_TIME) >= TO_DATE('2026-01-01','YYYY-MM-DD')
) t
JOIN ODS.M_INF_FXHIS_ACTIVITY act ON TRIM(TO_CHAR(act.PATIENT_ID))=TRIM(TO_CHAR(t.PATIENT_ID)) AND TRIM(TO_CHAR(act.SERIAL_NUMBER))=TRIM(TO_CHAR(t.SERIAL_NUMBER))
JOIN HIS.PAT_MASTER_INDEX pat ON TRIM(TO_CHAR(pat.PATIENT_ID))=TRIM(TO_CHAR(t.PATIENT_ID))
WITH READ ONLY;

