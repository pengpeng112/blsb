-- 传染病上报 · 入院记录（emr_admission_info，接口 2.2.3 / emrAdmissionInfo）V_INF_ADMISSION_INFO
-- 版本：2026-11-15 v1（我方接管他方 FXHIS.V_EMR_ADMISSION_INFO，用户拍板）
-- 参考：ODS.V_EMR_ADMISSION_RECORD（三甲）驱动口径 = 嘉和文书分类码 MR_CLASS='EMR09.00.01'
--       + NVL(DELETE_FLAG,0)=0 + 每就诊首份（ROW_NUMBER）；列集=FXHIS 版（平台已受理契约）。
-- 与他方版差异（修复其缺陷）：
--   ① 主诉/现病史/查体/辅查 = 嘉和正文真实内容（他方全为'暂无此内容'占位）；
--   ② 初步诊断=DIAGNOSIS TYPE=2 入院诊断（国标映射），不再全 TYPE 混入；确定诊断同源同链；
--   ③ operation_time=文书 NVL(修订,创建) 时间（他方=首诊断日期可为空）——T+0 水位稳。
-- 关联与及时性（硬口径）：
--   id=PATIENT_ID‖VISIT_ID、serial=INP_NO‖VISIT_ID（与他方历史一致，接管无重复）；
--   诊疗锚点 EXISTS（M_INF_FXHIS_ACTIVITY）+ 患者主索引 JOIN——无诊疗记录不上报；
--   推送器 payload operationTime=上传时刻（既有机制），及时率≈100%。
-- 【v1.1 2026-11-15】首推实测 errorCode 04（平台必填"确定诊断-西医诊断代码/名称"）：
--   确定诊断加兜底链 TYPE=2(入院)→TYPE=1(门急诊)→TYPE=3(出院)——他方版用全 TYPE listagg 故不空的根因同此。
-- 窗口：文书创建>=2026-01-01。DBA 执行；回滚 DROP VIEW。
-- =============================================================================
CREATE OR REPLACE FORCE VIEW "ODS"."V_INF_ADMISSION_INFO" (
  "ID","PATIENT_ID","SERIAL_NUMBER","PATIENT_NAME",
  "ID_CARD_TYPE_CODE","ID_CARD_TYPE_NAME","ID_CARD",
  "BED_NO","WARD_CODE","WARD_NAME","DEPT_CODE","DEPT_NAME",
  "ADMISSION_DATE",
  "WM_INITAL_DIAGNOSIS_CODE","WM_INITAL_DIAGNOSIS_NAME",
  "WM_CONFIRMED_DIAGNOSIS_CODE","WM_CONFIRMED_DIAGNOSIS_NAME",
  "CONFIRMED_DIAGNOSIS_DATE",
  "CHIEF_COMPLAINT","PRESENT_ILLNESS_HIS","PHYSICAL_EXAMINATION","STUDIES_SUMMARY_RESULT",
  "ORG_CODE","ORG_NAME","OPERATOR_ID","OPERATION_TIME"
) AS
WITH w AS (
  SELECT d.PATIENT_ID, d.VISIT_ID, d.FILE_UNIQUE_ID,
         d.CREATOR_ID, d.CREATE_DATE_TIME, d.LAST_MODIFY_DATE_TIME,
         ROW_NUMBER() OVER (PARTITION BY d.PATIENT_ID, d.VISIT_ID
                            ORDER BY d.CREATE_DATE_TIME, ROWID) rn
    FROM JHEMR.JHMR_FILE_INDEX d
   WHERE d.MR_CLASS = 'EMR09.00.01'
     AND NVL(d.DELETE_FLAG,0) = 0
     AND d.CREATE_DATE_TIME >= DATE'2026-01-01'
)
SELECT
  w.PATIENT_ID||'_'||w.VISIT_ID AS ID,
  w.PATIENT_ID AS PATIENT_ID,
  pmi.INP_NO||w.VISIT_ID AS SERIAL_NUMBER,
  pmi.NAME AS PATIENT_NAME,
  '01' AS ID_CARD_TYPE_CODE,
  '居民身份证' AS ID_CARD_TYPE_NAME,
  NVL(pmi.ID_NO,'-') AS ID_CARD,
  NVL(p.BED_NO, pv.DISCHARGE_BED_NO) AS BED_NO,
  NVL(p.WARD_CODE, pv.DISCHARGE_WARD_CODE) AS WARD_CODE,
  (SELECT MAX(b.DEPT_NAME) FROM HIS.DEPT_DICT b WHERE b.DEPT_CODE=NVL(p.WARD_CODE,pv.DISCHARGE_WARD_CODE)) AS WARD_NAME,
  NVL((SELECT MAX(dd.INFECT_DEPT_CODE) FROM HIS.INFECT_DEPT_DICT dd WHERE dd.HIS_DEPT_CODE=pv.DEPT_ADMISSION_TO), TO_CHAR(pv.DEPT_ADMISSION_TO)) AS DEPT_CODE,
  NVL((SELECT MAX(x.INFECT_DEPT_NAME) FROM HIS.INFECT_DEPT_DICT x WHERE x.HIS_DEPT_CODE=pv.DEPT_ADMISSION_TO),
      (SELECT MAX(b.DEPT_NAME) FROM HIS.DEPT_DICT b WHERE b.DEPT_CODE=pv.DEPT_ADMISSION_TO)) AS DEPT_NAME,
  pv.ADMISSION_DATE_TIME AS ADMISSION_DATE,
  (SELECT SUBSTRB(LISTAGG(NVL((SELECT MAX(TO_CHAR(cd.国标编码)) FROM CDA.CDA_DICTIONARY cd WHERE cd.字典名称='ICD-10诊断编码' AND cd.系统标识='HIS' AND cd.院标编码=dg.DIAGNOSIS_CODE), dg.DIAGNOSIS_CODE),'||') WITHIN GROUP (ORDER BY dg.DIAGNOSIS_NO),1,400)
     FROM HIS.DIAGNOSIS dg WHERE dg.PATIENT_ID=w.PATIENT_ID AND dg.VISIT_ID=w.VISIT_ID AND dg.DIAGNOSIS_TYPE='2' AND dg.DIAGNOSIS_CODE IS NOT NULL) AS WM_INITAL_DIAGNOSIS_CODE,  -- 初步=TYPE2 原样（平台未点名必填）,
  (SELECT SUBSTRB(LISTAGG(dg.DIAGNOSIS_DESC,'||') WITHIN GROUP (ORDER BY dg.DIAGNOSIS_NO),1,400)
     FROM HIS.DIAGNOSIS dg WHERE dg.PATIENT_ID=w.PATIENT_ID AND dg.VISIT_ID=w.VISIT_ID AND dg.DIAGNOSIS_TYPE='2' AND dg.DIAGNOSIS_CODE IS NOT NULL) AS WM_INITAL_DIAGNOSIS_NAME,
  NVL((SELECT SUBSTRB(LISTAGG(NVL((SELECT MAX(TO_CHAR(cd.国标编码)) FROM CDA.CDA_DICTIONARY cd WHERE cd.字典名称='ICD-10诊断编码' AND cd.系统标识='HIS' AND cd.院标编码=dg.DIAGNOSIS_CODE), dg.DIAGNOSIS_CODE),'||') WITHIN GROUP (ORDER BY dg.DIAGNOSIS_NO),1,400)
     FROM HIS.DIAGNOSIS dg WHERE dg.PATIENT_ID=w.PATIENT_ID AND dg.VISIT_ID=w.VISIT_ID AND dg.DIAGNOSIS_TYPE='2' AND dg.DIAGNOSIS_CODE IS NOT NULL),
  NVL((SELECT SUBSTRB(LISTAGG(NVL((SELECT MAX(TO_CHAR(cd.国标编码)) FROM CDA.CDA_DICTIONARY cd WHERE cd.字典名称='ICD-10诊断编码' AND cd.系统标识='HIS' AND cd.院标编码=dg.DIAGNOSIS_CODE), dg.DIAGNOSIS_CODE),'||') WITHIN GROUP (ORDER BY dg.DIAGNOSIS_NO),1,400)
     FROM HIS.DIAGNOSIS dg WHERE dg.PATIENT_ID=w.PATIENT_ID AND dg.VISIT_ID=w.VISIT_ID AND dg.DIAGNOSIS_TYPE='1' AND dg.DIAGNOSIS_CODE IS NOT NULL),
     (SELECT SUBSTRB(LISTAGG(NVL((SELECT MAX(TO_CHAR(cd.国标编码)) FROM CDA.CDA_DICTIONARY cd WHERE cd.字典名称='ICD-10诊断编码' AND cd.系统标识='HIS' AND cd.院标编码=dg.DIAGNOSIS_CODE), dg.DIAGNOSIS_CODE),'||') WITHIN GROUP (ORDER BY dg.DIAGNOSIS_NO),1,400)
     FROM HIS.DIAGNOSIS dg WHERE dg.PATIENT_ID=w.PATIENT_ID AND dg.VISIT_ID=w.VISIT_ID AND dg.DIAGNOSIS_TYPE='3' AND dg.DIAGNOSIS_CODE IS NOT NULL))) AS WM_CONFIRMED_DIAGNOSIS_CODE,
  NVL((SELECT SUBSTRB(LISTAGG(dg.DIAGNOSIS_DESC,'||') WITHIN GROUP (ORDER BY dg.DIAGNOSIS_NO),1,400)
     FROM HIS.DIAGNOSIS dg WHERE dg.PATIENT_ID=w.PATIENT_ID AND dg.VISIT_ID=w.VISIT_ID AND dg.DIAGNOSIS_TYPE='2' AND dg.DIAGNOSIS_CODE IS NOT NULL),
  NVL((SELECT SUBSTRB(LISTAGG(dg.DIAGNOSIS_DESC,'||') WITHIN GROUP (ORDER BY dg.DIAGNOSIS_NO),1,400)
     FROM HIS.DIAGNOSIS dg WHERE dg.PATIENT_ID=w.PATIENT_ID AND dg.VISIT_ID=w.VISIT_ID AND dg.DIAGNOSIS_TYPE='1' AND dg.DIAGNOSIS_CODE IS NOT NULL),
     (SELECT SUBSTRB(LISTAGG(dg.DIAGNOSIS_DESC,'||') WITHIN GROUP (ORDER BY dg.DIAGNOSIS_NO),1,400)
     FROM HIS.DIAGNOSIS dg WHERE dg.PATIENT_ID=w.PATIENT_ID AND dg.VISIT_ID=w.VISIT_ID AND dg.DIAGNOSIS_TYPE='3' AND dg.DIAGNOSIS_CODE IS NOT NULL))) AS WM_CONFIRMED_DIAGNOSIS_NAME,
  (SELECT MAX(dg.DIAGNOSIS_DATE) FROM HIS.DIAGNOSIS dg WHERE dg.PATIENT_ID=w.PATIENT_ID AND dg.VISIT_ID=w.VISIT_ID AND dg.DIAGNOSIS_CODE IS NOT NULL) AS CONFIRMED_DIAGNOSIS_DATE,
  DBMS_LOB.SUBSTR(c.MR_CONTENT, 2000, 1) AS CHIEF_COMPLAINT,   -- 入院记录正文（主诉节在文内；整段初版，节点解析二期）
  CAST(NULL AS VARCHAR2(2000)) AS PRESENT_ILLNESS_HIS,
  CAST(NULL AS VARCHAR2(2000)) AS PHYSICAL_EXAMINATION,
  CAST(NULL AS VARCHAR2(2000)) AS STUDIES_SUMMARY_RESULT,
  '370104000' AS ORG_CODE,
  '山东省第二人民医院' AS ORG_NAME,
  TO_CHAR(w.CREATOR_ID) AS OPERATOR_ID,
  NVL(w.LAST_MODIFY_DATE_TIME, w.CREATE_DATE_TIME) AS OPERATION_TIME
FROM w
JOIN JHEMR.JHMR_FILE_CONTENT_TEXT c ON c.FILE_UNIQUE_ID = w.FILE_UNIQUE_ID
JOIN HIS.PAT_MASTER_INDEX pmi ON pmi.PATIENT_ID = w.PATIENT_ID
LEFT JOIN HIS.PAT_VISIT pv ON pv.PATIENT_ID=w.PATIENT_ID AND pv.VISIT_ID=w.VISIT_ID
LEFT JOIN HIS.PATS_IN_HOSPITAL p ON p.PATIENT_ID=w.PATIENT_ID AND p.VISIT_ID=w.VISIT_ID
WHERE w.rn = 1
  AND EXISTS (SELECT 1 FROM ODS.M_INF_FXHIS_ACTIVITY act
              WHERE TRIM(act.PATIENT_ID)=TRIM(w.PATIENT_ID)
                AND TRIM(act.SERIAL_NUMBER)=TRIM(pmi.INP_NO||w.VISIT_ID))
WITH READ ONLY;

