-- 变更（相对在库 v0.5）：整段原逻辑包为内联 t，外层 INNER JOIN 两张 FXHIS 锚点镜像——
--   M_INF_FXHIS_ACTIVITY（patient_id+serial_number 双键）与 本地 HIS.PAT_MASTER_INDEX（患者锚点，同源实时镜像），
--   锚点无对应行的就诊不再上报（平台关联失败预防）。**列名/顺序与 v0.5 完全一致**，推送器零改动。
--   增量行为不变：日常 T+0 行天然在锚点窗内；本过滤只挡窗外历史/补传行。
-- 锚点依赖：ODS.M_INF_FXHIS_ACTIVITY（住院活动镜像）+ 本地 HIS.PAT_MASTER_INDEX（患者，同源实时）
