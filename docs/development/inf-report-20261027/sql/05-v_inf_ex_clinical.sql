-- 已知陷阱：EXAM_CLASS 存中文（'CT'/'磁共振'/'B超'…），非字典内码（平台资产02§5）
-- 检查类别值域仅 3 值（10影像学/11病理/99其它）；内镜/心电归类待确认（FIELD_MAPPING §5）
-- 本期范围：住院检查（PATIENT_SOURCE='I'）；门诊检查是否推送待用户定
