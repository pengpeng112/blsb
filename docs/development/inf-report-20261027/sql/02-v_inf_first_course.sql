-- 源：JHEMR.JHMR_FILE_INDEX + JHMR.JHMR_FILE_CONTENT_TEXT（嘉和文书索引+纯文本正文）
-- 模式参考：三甲 V_EMR_HOS_POSTOPER_RECORD_JHEMR（TOPIC 匹配 + NVL(DELETE_FLAG,0)=0 + pat_visit 关联）
-- 注意：TOPIC 过滤为保守写法（排除"术后"），真实 TOPIC 分布抽样后收紧（FIELD_MAPPING §7.3）
-- =============================================================================

CREATE OR REPLACE FORCE VIEW "ODS"."V_INF_FIRST_COURSE" (
  "ID", "PATIENT_ID", "SERIAL_NUMBER", "PATIENT_NAME",
  "ID_CARD_TYPE_CODE", "ID_CARD_TYPE_NAME", "ID_CARD",
  "WARD_NAME", "WARD_NO", "BED_NO", "CREATE_TIME",
  "CHIEF_COMPLAINT", "PRESENT_ILLNESS_HIS", "OBSERVATION_RESULT",
  "DIAGNOSIS_BASIS",
  "WM_INITAL_DIAGNOSIS_CODE", "WM_INITAL_DIAGNOSIS_NAME",
  "TCM_INITAL_DIAGNOSIS_CODE", "TCM_INITAL_DIAGNOSIS_NAME",
  "TCM_INITAL_SYNDROME_CODE", "TCM_INITAL_SYNDROME_NAME",
  "WM_DIFF_DIAGNOSIS_CODE", "WM_DIFF_DIAGNOSIS_NAME",
  "TREATMENT", "TREATMENT_PLAN",
  "DISEASE_PROGRESSION_CODE", "DISEASE_PROGRESSION_NAME",
  "RESIDENT_PHYSICIAN_ID",
  "ORG_CODE", "ORG_NAME", "DEPT_CODE", "DEPT_NAME",
  "OPERATOR_ID", "OPERATION_TIME"
) AS
SELECT
  t.PATIENT_ID || '_' || t.VISIT_ID || '_' || t.FILE_UNIQUE_ID AS ID,

  t.PATIENT_ID AS PATIENT_ID,
  pmi.INP_NO || t.VISIT_ID AS SERIAL_NUMBER,  -- crbsb 口径=病案号||住院次数
  SUBSTRB(TO_CHAR(pmi.NAME), 1, 100) AS PATIENT_NAME,

  '01' AS ID_CARD_TYPE_CODE,
  '居民身份证' AS ID_CARD_TYPE_NAME,
  NVL(TO_CHAR(pmi.ID_NO), '-') AS ID_CARD,  -- crbsb 同款兜底

  NVL((SELECT MAX(dd.INFECT_DEPT_NAME) FROM HIS.INFECT_DEPT_DICT dd WHERE TO_CHAR(dd.HIS_DEPT_CODE) = TO_CHAR(t.DEPT_CODE)), TO_CHAR(t.DEPT_CODE)) AS WARD_NAME,  -- 病区名称初版=科室名，INFECT 映射+兜底
  CAST(NULL AS VARCHAR2(10)) AS WARD_NO,
  SUBSTRB(TO_CHAR(t.FILE_NO), 1, 10) AS BED_NO,                  -- 三甲术后首程同口径（FILE_NO→床号）
  t.CREATE_DATE_TIME AS CREATE_TIME,

  CAST(NULL AS VARCHAR2(2000)) AS CHIEF_COMPLAINT,               -- 主诉结构化二期（CDA/DG 节点，见 FIELD_MAPPING §2）
  DBMS_LOB.SUBSTR(c.MR_CONTENT, 2000, 1) AS PRESENT_ILLNESS_HIS, -- 病例特点=正文整段（建议填）；截2000字=GBK库SQL层VARCHAR2 4000字节上限（实测3900字触发ORA-06502，三甲同款2000）；全文推送二期走CLOB直读
  CAST(NULL AS VARCHAR2(2000)) AS OBSERVATION_RESULT,            -- 中医四诊，非必填
  CAST(NULL AS VARCHAR2(2000)) AS DIAGNOSIS_BASIS,               -- 诊断依据二期

  CAST(NULL AS VARCHAR2(400)) AS WM_INITAL_DIAGNOSIS_CODE,       -- 初步诊断二期（jhemr.diagnosis 入院诊断关联）
  CAST(NULL AS VARCHAR2(400)) AS WM_INITAL_DIAGNOSIS_NAME,
  CAST(NULL AS VARCHAR2(250)) AS TCM_INITAL_DIAGNOSIS_CODE,
  CAST(NULL AS VARCHAR2(250)) AS TCM_INITAL_DIAGNOSIS_NAME,
  CAST(NULL AS VARCHAR2(250)) AS TCM_INITAL_SYNDROME_CODE,
  CAST(NULL AS VARCHAR2(250)) AS TCM_INITAL_SYNDROME_NAME,
  CAST(NULL AS VARCHAR2(400)) AS WM_DIFF_DIAGNOSIS_CODE,
  CAST(NULL AS VARCHAR2(400)) AS WM_DIFF_DIAGNOSIS_NAME,
  CAST(NULL AS VARCHAR2(100)) AS TREATMENT,
  CAST(NULL AS VARCHAR2(2000)) AS TREATMENT_PLAN,
  CAST(NULL AS VARCHAR2(1))  AS DISEASE_PROGRESSION_CODE,
  CAST(NULL AS VARCHAR2(50)) AS DISEASE_PROGRESSION_NAME,

  TO_CHAR(t.CREATOR_ID) AS RESIDENT_PHYSICIAN_ID,                -- 须在 base_user 值域

  '370104000' AS ORG_CODE,
  '山东省第二人民医院' AS ORG_NAME,
  NVL((SELECT MAX(dd.INFECT_DEPT_CODE) FROM HIS.INFECT_DEPT_DICT dd WHERE TO_CHAR(dd.HIS_DEPT_CODE) = TO_CHAR(t.DEPT_CODE)), TO_CHAR(t.DEPT_CODE)) AS DEPT_CODE,  -- crbsb 口径 INFECT 映射+原码兜底
  NVL((SELECT MAX(x.INFECT_DEPT_NAME) FROM HIS.INFECT_DEPT_DICT x
      WHERE TO_CHAR(x.HIS_DEPT_CODE) = TO_CHAR(t.DEPT_CODE)),
      (SELECT MAX(dd.DEPT_NAME) FROM HIS.DEPT_DICT dd
      WHERE TO_CHAR(dd.DEPT_CODE) = TO_CHAR(t.DEPT_CODE))) AS DEPT_NAME,

  NVL(TO_CHAR(t.LAST_MODIFY_USER_ID), TO_CHAR(t.CREATOR_ID)) AS OPERATOR_ID,
  NVL(t.LAST_MODIFY_DATE_TIME, t.CREATE_DATE_TIME) AS OPERATION_TIME  -- 增量水位
FROM JHEMR.JHMR_FILE_INDEX t
JOIN JHEMR.JHMR_FILE_CONTENT_TEXT c ON c.FILE_UNIQUE_ID = t.FILE_UNIQUE_ID
JOIN HIS.PAT_VISIT pv ON pv.PATIENT_ID = t.PATIENT_ID AND pv.VISIT_ID = t.VISIT_ID
JOIN HIS.PAT_MASTER_INDEX pmi ON pmi.PATIENT_ID = t.PATIENT_ID
WHERE t.TOPIC LIKE '%首次病程记录%'
  AND t.TOPIC NOT LIKE '%术后%'                                   -- 排除术后首次病程记录
  AND NVL(t.DELETE_FLAG, 0) = 0
  AND NVL(t.LAST_MODIFY_DATE_TIME, t.CREATE_DATE_TIME) >= TO_DATE('2026-01-01', 'YYYY-MM-DD')
WITH READ ONLY;
