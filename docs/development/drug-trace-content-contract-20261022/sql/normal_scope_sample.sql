-- 限当天索引窗口与100个父键；只观察原值分布，不把样本解释成人工批准。
SELECT PRESC_SOURCE,FLAG,REFUND_FLAG,TRACE_STATUS,COUNT(*) AS SAMPLE_BILLS
FROM (
    SELECT M.PRESC_SOURCE,M.FLAG,M.REFUND_FLAG,M.TRACE_STATUS
    FROM PHARMACY.DRUG_PRESC_MASTER M
    WHERE M.DISPENSING_DATETIME>=TO_DATE('2026-10-22','yyyy-mm-dd')
      AND M.DISPENSING_DATETIME<TO_DATE('2026-10-23','yyyy-mm-dd')
      AND ROWNUM<=100
)
GROUP BY PRESC_SOURCE,FLAG,REFUND_FLAG,TRACE_STATUS
