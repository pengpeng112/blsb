SELECT OWNER,TABLE_NAME,COLUMN_NAME,DUMP(COMMENTS,16) AS COMMENT_BYTES
FROM ALL_COL_COMMENTS
WHERE (OWNER='PHARMACY' AND TABLE_NAME='DRUG_PRESC_MASTER'
       AND COLUMN_NAME IN ('PRESC_DATE','PRESC_NO','DISPENSARY','PRESC_SOURCE',
          'DISPENSING_DATETIME','FLAG','REFUND_FLAG','TRACE_STATUS'))
   OR (OWNER='DRUG_USER' AND TABLE_NAME='MED_TRACE_RECORD'
       AND COLUMN_NAME IN ('RECORD_ID','PRESC_DETAILID','CREATE_TIME','T_TRACE_CODE',
          'IN_OUT_TYPE','IS_DELETED','SPLIT_FLAG','TRACES_SUM'))
ORDER BY OWNER,TABLE_NAME,COLUMN_NAME
