-- 完整三字段关联只做受限样本核验，最多20个父键、100行子表，不返回真实标识或码。
SELECT HEADER_SOURCE,HEADER_FLAG,REFUND_FLAG,IN_OUT_TYPE,IS_DELETED,SPLIT_FLAG,
       COUNT(*) AS SAMPLE_RECORDS,
       SUM(CASE WHEN LENGTH(T_TRACE_CODE)=20
                 AND REGEXP_LIKE(T_TRACE_CODE,'^[0-9]+$') THEN 1 ELSE 0 END) AS CODES_20_DIGITS,
       SUM(CASE WHEN PRESC_DETAILID IS NULL THEN 1 ELSE 0 END) AS MISSING_DETAIL_ID,
       SUM(CASE WHEN TRACES_SUM>1 THEN 1 ELSE 0 END) AS TRACES_SUM_GT_1
FROM (
    SELECT M.PRESC_SOURCE AS HEADER_SOURCE,M.FLAG AS HEADER_FLAG,M.REFUND_FLAG,
           T.IN_OUT_TYPE,T.IS_DELETED,T.SPLIT_FLAG,T.T_TRACE_CODE,T.PRESC_DETAILID,T.TRACES_SUM
    FROM (
        SELECT PRESC_DATE,PRESC_NO,DISPENSARY,PRESC_SOURCE,FLAG,REFUND_FLAG
        FROM PHARMACY.DRUG_PRESC_MASTER
        WHERE DISPENSING_DATETIME>=TO_DATE('2026-10-22','yyyy-mm-dd')
          AND DISPENSING_DATETIME<TO_DATE('2026-10-23','yyyy-mm-dd')
          AND ROWNUM<=20
    ) M
    JOIN DRUG_USER.MED_TRACE_RECORD T
      ON T.TRACE_BILLNO=TO_CHAR(M.PRESC_NO)
     AND T.PRESC_DATE=M.PRESC_DATE
     AND T.STORE_CODE=M.DISPENSARY
    WHERE ROWNUM<=100
)
GROUP BY HEADER_SOURCE,HEADER_FLAG,REFUND_FLAG,IN_OUT_TYPE,IS_DELETED,SPLIT_FLAG
